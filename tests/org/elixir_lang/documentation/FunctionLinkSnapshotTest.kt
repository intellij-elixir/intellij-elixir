package org.elixir_lang.documentation

import com.intellij.psi.PsiElement
import com.intellij.psi.PsiFile
import com.intellij.psi.ResolveResult
import com.intellij.psi.util.PsiTreeUtil
import org.elixir_lang.psi.call.Call
import org.elixir_lang.snapshot.ResolutionSnapshot
import org.elixir_lang.snapshot.SnapshotTestCase

/**
 * Fails when what a function or callback link finds, whether it is linked and what it opens differ from the committed
 * snapshot.
 */
class FunctionLinkSnapshotTest : SnapshotTestCase() {
    fun testFunctionLinks() {
        val (root, files) = copyInputs("documentation/function_link")
        myFixture.copyFileToProject("psi/callable_declaration/eex.ex", "eex.ex")
        val snapshot = ResolutionSnapshot(root)

        val lines = LINKS.flatMap { (module, links) ->
            val context = modular(files.single { "defmodule $module do" in it.text }, module)

            links.map { link ->
                val parsed = DocumentationLink.parse(link)!!
                val callback = parsed.kind == "c"
                val arity = parsed.arity!!
                val results = FunctionLink.results(context, parsed.module, parsed.name, arity)
                val exists = FunctionLink.exists(context, parsed.module, parsed.name, arity, callback)
                val target = FunctionLink.target(context, parsed.module, parsed.name, arity, callback)

                "`$link`  in $module  ->  ${describe(snapshot, results)}  exists=$exists  " +
                    "target=${target?.let { location(snapshot, it) } ?: "none"}"
            }
        }

        assertGolden("documentation/function_link.txt", HEADER, lines, REGENERATE)
    }

    private fun modular(file: PsiFile, module: String): Call =
        PsiTreeUtil.findChildrenOfType(file, Call::class.java).first { it.text.startsWith("defmodule $module do") }

    private fun describe(snapshot: ResolutionSnapshot, results: List<ResolveResult>): String =
        results.joinToString(" | ") {
            location(snapshot, it.element!!) + if (it.isValidResult) "" else " (invalid)"
        }.ifEmpty { "nothing" }

    private fun location(snapshot: ResolutionSnapshot, element: PsiElement): String =
        snapshot.location(element.containingFile, element.textRange)

    private companion object {
        const val REGENERATE =
            "./gradlew test --tests org.elixir_lang.documentation.FunctionLinkSnapshotTest -PoverwriteTestData=true"

        val HEADER = listOf(
            "# Generated by FunctionLinkSnapshotTest: do not edit. Regenerate with $REGENERATE",
            "# Per link, as written in the context module: the definitions it names in the order found, `(invalid)` where",
            "# the walk marks one invalid, whether it is linked, and the one it opens:",
            "#   `link`  in module  ->  file:line:column [(invalid)] | ...  exists=<boolean>  target=file:line:column",
            "# Review each moved line in a diff.",
        )

        /** The context module of each group, and the links written in it. */
        val LINKS = listOf(
            "Basics" to listOf(
                "both/1", "plain/1", "two/1", "two/2", "missing/1",
                "Basics.both/1", "c:Basics.both/1", "Basics.only_callback/1", "c:Basics.only_callback/1",
                "Basics.plain/1", "c:Basics.plain/1", "Basics.two/1", "Basics.two/2", "Basics.missing/1",
                "Basics.delegated/1", "Basics.delegated/2", "Target.delegated/1",
                ":atom_module.plain/1", ":\"Elixir.Basics\".plain/1",
            ),
            "Prefixed" to listOf(
                "Prefixed.foo/1", "Prefixed.foo/2", "PrefixOnly.foo/1", "PrefixOnly.foo_bar/1",
                "LongerFirst.foo/1", "LongerFirst.foo/2", "ShorterFirst.foo/1", "ShorterFirst.foo/2",
                "c:LongerCallback.foo/1", "c:LongerCallback.foo_bar/1", "c:LongerCallbackFirst.foo/1",
                "c:LongerCallbackFirst.foo/2",
            ),
            "OpenDelegator" to listOf(
                "OpenTarget.open/2", "OpenTarget.open/3", "OpenDelegator.open/2", "OpenDelegator.open/3",
                "OpenDelegator.open/4", "open/2", "open/4",
            ),
            "Views" to listOf(
                "Views.listed/1", "Views.listed/2", "Views.opaque/0", "Views.opaque/1", "Views.open_tail/0",
                "Views.open_tail/1", "Views.open_tail/2", "Views.open_tail/3", "Views.\"quoted_eex\"/1",
                "Views.quoted_eex/1", "open_tail/1",
            ),
        )
    }
}
