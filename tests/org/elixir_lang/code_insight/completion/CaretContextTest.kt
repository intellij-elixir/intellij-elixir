/** [CaretContext] gives `Code.Fragment.cursor_context/2`'s answer for the text before the caret, as Elixir 1.20.4 gives it. */
class CaretContextTest : PlatformTestCase() {
    fun testElixirsAnswers() = assertElixirsAnswers(ROWS.map { (text, elixir) -> Triple("caret.ex", text, elixir) })

    /** In a template, Elixir's tools give `cursor_context` the tag's code alone, so the tag's markers are not text before the caret. */
    fun testTemplates() = assertElixirsAnswers(TEMPLATE_ROWS)

    /**
     * A `#` in a string or a character starts no comment, so the line before still ends in its dot. Elixir's text cut
     * reads a comment from it, and gives `{:local_or_var, ~c"baz"}`.
     */
    fun testAHashInAStringOrCharacterStartsNoComment() {
        for (text in listOf("foo(\"#\", bar.\n  baz<caret>", "foo(?#, bar.\n  baz<caret>")) {
            myFixture.configureByText("caret.ex", text)

            assertEquals(text, "{:dot, {:var, ~c\"bar\"}, ~c\"baz\"}", CaretContext.at(myFixture.file, myFixture.caretOffset).toString())
        }
    }

    /** Each of [rows], a file name, its text with the caret marked and Elixir's answer, gives Elixir's answer in the file's Elixir tree. */
    private fun assertElixirsAnswers(rows: List<Triple<String, String, String>>) {
        val differing = rows.mapNotNull { (file, text, elixir) ->
            myFixture.configureByText(file, text)
            val elixirRoot = myFixture.file.viewProvider.getPsi(ElixirLanguage)!!
            val plugin = CaretContext.at(elixirRoot, myFixture.caretOffset).toString()

            "$file ${text.replace("\n", "\\n")}: Elixir $elixir, plugin $plugin".takeIf { plugin != elixir }
        }

        assertEquals("texts whose context is not Elixir's", "", differing.joinToString("\n"))
    }

