package org.elixir_lang.code_insight.matrix

import junit.framework.TestCase
import org.elixir_lang.beam.BeamReader
import org.elixir_lang.beam.chunk.CallDefinitions
import org.elixir_lang.beam.decompiler.clauseSource
import java.io.File
import java.security.MessageDigest

/** The generated fixtures are what the matrix assumes: current, compiled as declared, and marked where the names are. */
class MatrixFixtureTest : TestCase() {
    /**
     * Asked of `local_site/2`, or a delegate target's `target_marker/0`, because their names are ASCII: how the
     * decompiler reads a world's own names, such as a non-ASCII look-alike, is behaviour the matrix's cells report,
     * not how the beam was built.
     */
    private val GENERATED = setOf("__info__", "module_info")

    fun testEachBeamDecompilesThroughItsClauseSource() {
        val wrong = Fixtures.oracle.scenarios.flatMap { it.modules }.filter { it.beam != null }.mapNotNull { module ->
            val beam = module.beam!!
            val bytes = Fixtures.file(beam).readBytes()
            // A module a `use` world's main module uses declares no definition of the world's own; any it has will do.
            val first = module.definitions.firstOrNull()

            val (name, actual) = BeamReader.read(bytes, beam) { reader ->
                val definitions = CallDefinitions.macroNameAritySortedSetByMacro(reader).values.flatten()
                val macroNameArity = definitions.firstOrNull { it.name == "local_site" && it.arity == 2 }
                    ?: definitions.firstOrNull { it.name == "target_marker" && it.arity == 0 }
                    ?: first?.let { first -> definitions.firstOrNull { nfc(it.name) == first.name && it.arity == first.maxArity } }
                    // What the compiler adds to every module - `__info__/1`, `module_info` - has no clause the author wrote.
                    ?: definitions.firstOrNull { it.name !in GENERATED }.takeIf { first == null }
                    ?: return@read "${first?.name}/${first?.maxArity}" to "no definition"

                "${macroNameArity.name}/${macroNameArity.arity}" to
                    (clauseSource(macroNameArity, reader.debugInfo) { reader.documentation }?.javaClass?.simpleName ?: "no clause source")
            }!!

            if (actual == module.clauseSource) null else "$beam $name: expected ${module.clauseSource}, got $actual"
        }

        assertEquals("Beams whose definitions decompile through the wrong clause source", emptyList<String>(), wrong)
    }

    /**
     * The oracle records which Elixir produced it. That is fixture *provenance*, not a property of the leg: CI
     * runs ten Elixir/OTP pairs, and the matrix is the same on all of them, because nothing it tests gates on the
     * language version and every expectation it reads is committed. So this pins the oracle against the toolchain
     * pin in `mise.toml` - catching a regeneration done on the wrong Elixir - and deliberately says nothing about
     * the pair the tests happen to be running under, which would redden nine legs out of ten.
     */
    fun testOracleWasGeneratedByThePinnedElixir() {
        val pin = File("mise.toml").readText()
        val pinned = Regex("""elixir\s*=\s*"([\d.]+)""").find(pin)?.groupValues?.get(1)
            ?: throw AssertionError("mise.toml does not pin an Elixir version")

        assertEquals(
            "oracle.json was generated by an Elixir other than mise.toml's pin; regenerate with the pinned toolchain",
            pinned,
            Fixtures.oracle.elixir
        )
    }

    /**
     * An Erlang beam stripped of its Docs chunk has nothing left to say which language it came from, so the plugin
     * reads it as Elixir. That one fact is the whole of what `erl_gen` establishes: asked the matrix's questions it
     * answered exactly as `ex_gen` did, over 1,090 comparable cells, without a single disagreement - because it runs
     * the same decompiler, not by luck. It is pinned here instead of by cells that would cost seconds and red to
     * re-learn it. If this fails, `erl_gen` has become a route of its own again and wants its cells back.
     */
    fun testDocslessErlangBeamIsReadAsElixir() {
        val module = Fixtures.oracle.scenarios
            .single { it.backing == "erl_gen" }
            .modules
            .single { it.beam != null }
        val beam = module.beam!!

        val actual = BeamReader.read(Fixtures.file(beam).readBytes(), beam) { reader ->
            val macroNameArity = CallDefinitions.macroNameAritySortedSetByMacro(reader).values.flatten()
                .first { it.name == "local_site" && it.arity == 2 }

            clauseSource(macroNameArity, reader.debugInfo) { reader.documentation }?.javaClass?.simpleName
        }

        assertEquals("A docs-stripped Erlang beam no longer falls back to the Elixir decompiler", "Generated", actual)
    }

    /**
     * A dependency compiled nine years of releases ago reads the same as one compiled today.
     *
     * Measured before this was written: the `Dbgi` map genuinely differs between 1.11.4 and 1.20.4 - `line` became
     * `anno`, `is_behaviour` became `defines_behaviour` - but every field the decompiler reads is identical, for
     * defaults with a bodiless head, guards, macros, `defdelegate` metadata, private functions and a non-ASCII
     * name alike. That is why provenance is one guard rather than a backing: an axis would have cost thousands of
     * cells that cannot disagree. What it still catches is a reader tuned for modern beams that stops reading old
     * dependencies, which is a plausible outcome of the migration this matrix exists to protect.
     */
    fun testAnOldElixirsBeamReadsTheSameAsTodays() {
        val old = decompiled("provenance/1.11.4/Elixir.Provenance.beam")
        val current = decompiled("provenance/${Fixtures.oracle.elixir}/Elixir.Provenance.beam")

        assertEquals(
            "A beam built by Elixir 1.11.4 no longer decompiles the same as one built by ${Fixtures.oracle.elixir}",
            current,
            old
        )
    }

    /**
     * Everything the decompiler takes from a beam, as one comparable string per definition the module declares.
     *
     * The compiler's own additions are excluded, because they are not what this compares: `module_info` and
     * `__info__` every module gets, and names beginning `-`, which are synthesised - Elixir 1.20 emits a
     * `-inlined-__info__/1-/1` that 1.11 did not. That the plugin shows such a name to a user at all is a defect,
     * but it is the compiler's difference rather than the reader's, and pinning it here would make this guard fail
     * for a reason it is not asking about.
     *
     * Sorted for the same reason. The order definitions come back in is the order the compiler wrote them into
     * the export table, and the two compilers disagree about it - 1.20.4 puts a `defmacro` first where 1.11.4 puts
     * it last - while every definition and everything read from it is identical. Comparing unsorted would make
     * this report a difference in the compilers as a difference in the reader.
     */
    private fun decompiled(path: String): List<String> =
        BeamReader.read(Fixtures.file(path).readBytes(), path) { reader ->
            CallDefinitions.macroNameAritySortedSetByMacro(reader).values.flatten()
                .filterNot { it.name.startsWith("-") || it.name == "module_info" || it.name == "__info__" }
                .map { macroNameArity ->
                    val clauseSource = clauseSource(macroNameArity, reader.debugInfo) { reader.documentation }

                    "${macroNameArity.macro} ${nfc(macroNameArity.name)}/${macroNameArity.arity} " +
                        "${clauseSource?.javaClass?.simpleName}(${clauseSource?.parameters?.joinToString(", ")}) " +
                        "generatedName=${clauseSource?.isAutoGeneratedName}"
                }
                .sorted()
        }!!

    fun testFixturesAreWhatGenerateExsWrote() {
        val changed = Fixtures.manifest.sha256.mapNotNull { (path, expected) ->
            val file = Fixtures.file(path)

            when {
                !file.exists() -> "$path is missing"
                sha256(file.readBytes()) != expected -> "$path changed since generate.exs wrote it"
                else -> null
            }
        }

        assertEquals("Fixtures edited without rerunning generate.exs", emptyList<String>(), changed)
    }

    fun testEverySitePointsAtItsName() {
        val misplaced = Fixtures.oracle.scenarios.flatMap { scenario ->
            // The site's own name, not its binding's: a call at an arity nothing covers has no binding, and a call
            // to a name nothing declares has neither a binding nor anything in the world to fall back to.
            val sites = scenario.sites.map { Triple(it.file, it.line to it.column, it.name) } +
                scenario.modules.flatMap { module -> module.declarations.map { Triple(it.file ?: module.source, it.line to it.column, it.spelled ?: it.name) } }

            sites.mapNotNull { (path, position, name) ->
                val line = Fixtures.file(path).readLines()[position.first - 1]
                val text = line.substring(position.second - 1)

                if (nfc(text).startsWith(nfc(name))) null else "$path:${position.first}:${position.second} is at `$text`, not `$name`"
            }
        }

        assertEquals("Sites whose position is not on the name", emptyList<String>(), misplaced)
    }

    private fun sha256(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
}
