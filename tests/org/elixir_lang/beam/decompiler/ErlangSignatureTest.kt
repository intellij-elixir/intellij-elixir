package org.elixir_lang.beam.decompiler

import com.intellij.psi.stubs.Stub
import org.elixir_lang.PlatformTestCase
import org.elixir_lang.beam.psi.BeamFileImpl
import org.elixir_lang.beam.psi.stubs.callDefinitionStubs
import java.io.File

/**
 * An Erlang function's stub names, in the order OTP's `beam_doc` picks a function's signature for its `Docs` chunk:
 * a one-clause `-spec` naming every argument, else a single clause's variables, else the first clause's head.
 * `erlang_signature.erl` beside the fixture is its source.
 */
class ErlangSignatureTest : PlatformTestCase() {
    fun testASpecNamesTheParametersOfAClauseOfPatterns() = assertNames("spec_names", 2, "key", "value")

    fun testASpecNamesTheParametersOfEveryClause() = assertNames("spec_over_clauses", 2, "key", "list")

    fun testAnAnnotatedSpecArgumentIsNamedByItsVariable() = assertNames("annotated", 1, "q")

    fun testSpecNamesAreRenderedAsTheDecompilerRendersAVariable() =
        assertNames("rendered", 2, "erlangVariableIn", "q1")

    fun testAnAnonymousSpecVariableIsAName() = assertNames("anonymous_spec", 1, "_")

    fun testASpecArgumentThatIsNoVariableFallsToTheClause() = assertNames("untyped_spec", 1, "value")

    fun testABoundedSpecNamesItsArguments() = assertNames("bounded", 1, "tuple")

    fun testASpecOfTwoClausesFallsToTheClause() = assertNames("two_clause_spec", 1, "x")

    fun testASpecWithTheModuleInItsNameIsTheFunctionsOwn() = assertNames("remote", 1, "tuple")

    fun testASpecAfterItsFunctionNamesIt() = assertNames("spec_after", 1, "tuple")

    // A `-callback` of the function's name and arity names the behaviour's callback, not the function.
    fun testAFunctionIsNamedByItsOwnSpecAndNotByACallbackOfItsNameAndArity() {
        assertNames("callback_named", 1, "{a, b}")
        assertNames("spec_then_callback", 1, "own")
    }

    fun testASingleClauseOfVariablesNamesTheParameters() = assertNames("args", 2, "first", "second")

    fun testALeadingUnderscoreIsTrimmedFromASingleClausesVariables() = assertNames("trimmed", 2, "acc", "value")

    fun testASingleClauseWithAnUnderscoreKeepsItsHead() = assertNames("underscore", 2, "_", "value")

    fun testASingleClauseWithAPatternKeepsItsHead() = assertNames("pattern", 2, "{x}", "y")

    fun testAFunctionOfManyClausesWithoutASpecKeepsItsFirstClausesHead() =
        assertNames("multi_clause", 2, "first", ":a")

    /** The chunk names `doc_line(Left, Right)` from the `-doc`'s first line, which the compiler strips. */
    fun testADocLineDoesNotNameTheParameters() = assertNames("doc_line", 2, "a", "b")

    fun testAnUnexportedFunctionIsNamedBySpec() = assertNames("private_spec", 1, "name", exported = false)

    fun testAnUnexportedFunctionIsNamedByItsSingleClause() =
        assertNames("private_trimmed", 1, "acc", exported = false)

    private fun assertNames(name: String, arity: Int, vararg parameters: String, exported: Boolean = true) {
        val stub = callDefinitionStubs(fileStub()).singleOrNull {
            it.name == name && it.callDefinitionClauseHeadArity() == arity
        }
        assertNotNull("no $name/$arity stub", stub)

        assertEquals("$name/$arity exported", exported, stub!!.isExported)
        assertEquals("$name/$arity parameters", parameters.toList(), stub.parameters())
        assertFalse("$name/$arity isAutoGeneratedName", stub.isAutoGeneratedName)
    }

    private fun fileStub(): Stub =
        BeamFileImpl.buildFileStub(File(FIXTURE).readBytes(), "erlang_signature.beam") ?: error("no stub built")

    private companion object {
        const val FIXTURE = "testData/org/elixir_lang/beam/decompiler/erlang_signature/erlang_signature.beam"
    }
}
