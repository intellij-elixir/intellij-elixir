# Records what the running Elixir's compiler says about the resolution snapshot's input directories: in
# `<version>/<input>.facts`, every reference it traced and what it resolved to, every alias it expanded, what each
# module defines, and the errors of files that do not compile. A fact's fields are separated by tabs, so a name may
# hold spaces.
#
# The facts are per Elixir version, so run this once with each Elixir CI tests, from this directory:
# `mise exec elixir@<elixir>-otp-<otp major> erlang@<otp> -- elixir generate.exs`. An argument writes the version
# directory under that directory instead.
#
# `elixir generate.exs <root> <name> <input> <test helper>` writes `<root>/<version>/<name>.facts` instead, from every
# `**/*_test.exs` under `<input>`, after requiring `<test helper>` untraced, with each path under `<name>/`.

defmodule CompilerFacts.Tracer do
  @sink {__MODULE__, :sink}
  @kinds [
    :remote_function,
    :remote_macro,
    :imported_function,
    :imported_macro,
    :imported_quoted,
    :local_function,
    :local_macro,
    :alias_reference
  ]

  def sink, do: @sink

  def trace(event, env) when is_tuple(event) and elem(event, 0) in @kinds do
    send(:persistent_term.get(@sink), {:event, env.file, env.module, env.aliases, event})
    :ok
  end

  def trace(_event, _env), do: :ok
end

defmodule CompilerFacts do
  @inputs [
    {"callable_declaration", "../../psi/callable_declaration"},
    {"columns", "columns"},
    {"inputs", "../inputs"}
  ]

  def run([root, name, input, helper]) do
    Code.put_compiler_option(:parser_options, columns: true)
    Code.put_compiler_option(:debug_info, true)
    Code.require_file(helper)
    Code.put_compiler_option(:tracers, [CompilerFacts.Tracer])
    header = "# Elixir #{System.version()}. Generated by generate.exs from the tests in #{name}."
    write(root, name, [header | facts(Path.expand(input), "**/*_test.exs", name)])
  end

  def run(argv) do
    root =
      case argv do
        [] -> __DIR__
        [root] -> root
      end

    Code.put_compiler_option(:parser_options, columns: true)
    Code.put_compiler_option(:debug_info, true)
    Code.put_compiler_option(:tracers, [CompilerFacts.Tracer])

    for {name, input} <- @inputs do
      write(root, name, [header() | facts(Path.expand(input, __DIR__), "*.ex", "")])
    end
  end

  defp write(root, name, lines) do
    directory = Path.join(root, System.version())
    File.mkdir_p!(directory)
    File.write!(Path.join(directory, name <> ".facts"), Enum.join(lines, "\n") <> "\n")
  end

  defp header do
    "# Elixir #{System.version()}. Generated by generate.exs; do not edit. Regenerate in " <>
      "testData/org/elixir_lang/snapshot/compiler with " <>
      "`mise exec elixir@<elixir>-otp-<otp major> erlang@<otp> -- elixir generate.exs`."
  end

  defp facts(input, pattern, prefix) do
    files = input |> Path.join(pattern) |> Path.wildcard() |> Enum.reject(&provided?/1)
    path = &Path.join(prefix, Path.relative_to(&1, input))
    {events, modules, errors} = compile(files, [], [], [])
    # Left loaded, a module would make the next input directory's file that defines it look provided.
    purge(modules)
    nodes = Map.new(files, &{&1, nodes(&1)})

    diagnostics =
      for {file, line, kind} <- errors do
        path = path.(file)
        {path, line, 0, fields(["diag", "#{path}:#{line}" | kind])}
      end

    # A test may require a file outside the inputs as it compiles, and the compiler reports that file's modules as the
    # test's; only the events and modules whose own source is an input are kept.
    positioned =
      for({file, _, _, _} = event <- events, is_map_key(nodes, file), line <- event_line(event, path, nodes), do: line) ++
        diagnostics

    definitions =
      for module <- modules, definition <- definition_lines(module, nodes) do
        definition
      end

    Enum.uniq(Enum.map(Enum.sort(positioned), &elem(&1, 3)) ++ Enum.map(Enum.sort(definitions), &elem(&1, 1)))
  end

  # A file whose modules the running Elixir already provides stands in for them; compiling it would replace them.
  defp provided?(file) do
    modules =
      case Code.string_to_quoted!(File.read!(file)) do
        {:__block__, _, forms} -> forms
        form -> [form]
      end
      |> Enum.flat_map(fn
        {:defmodule, _, [{:__aliases__, _, segments} | _]} -> [Module.concat(segments)]
        _ -> []
      end)

    modules != [] and Enum.all?(modules, &Code.ensure_loaded?/1)
  end

  # The compiler stops every other file at the first file that fails, so which failing file it reports is a race.
  defp compile([], events, modules, errors), do: {events, modules, errors}

  defp compile(files, events, modules, errors) do
    {result, round_events, round_modules} = compile_round(files)

    case result do
      {:ok, _, _} ->
        {events ++ round_events, modules ++ round_modules, errors}

      # The last error is the one that stopped the round. The errors before it may include some that files it then
      # stopped had already reported, so only its file's are kept.
      {:error, round_errors, _} ->
        failed = round_errors |> List.last() |> error_file()

        failed_errors =
          for error <- round_errors, error_file(error) == failed, kind = error_kind(error), kind != :logged do
            {failed, error_line(error), kind}
          end

        purge(round_modules)

        compile(
          List.delete(files, failed),
          events ++ Enum.filter(round_events, &(elem(&1, 0) == failed)),
          modules ++ Enum.filter(round_modules, &(elem(&1, 0) == failed)),
          errors ++ failed_errors
        )
    end
  end

  defp purge(modules) do
    for {_, module, _} <- modules do
      :code.purge(module)
      :code.delete(module)
    end
  end

  # On 1.14 a round started in the process of a round the compiler stopped never returns.
  defp compile_round(files) do
    parent = self()

    {pid, monitor} =
      spawn_monitor(fn ->
        caller = self()
        :persistent_term.put(CompilerFacts.Tracer.sink(), caller)
        each_module = fn file, module, binary -> send(caller, {:module, file, module, binary}) end
        result = Kernel.ParallelCompiler.compile(files, each_module: each_module, return_diagnostics: true)
        {events, modules} = drain([], [])
        send(parent, {:round, self(), result, events, modules})
      end)

    receive do
      {:round, ^pid, result, events, modules} ->
        Process.demonitor(monitor, [:flush])
        {result, events, modules}

      {:DOWN, ^monitor, :process, ^pid, reason} ->
        raise "a compilation round exited: #{inspect(reason)}"
    end
  end

  defp drain(events, modules) do
    receive do
      {:event, file, module, aliases, event} -> drain([{file, module, aliases, event} | events], modules)
      {:module, file, module, binary} -> drain(events, [{file, module, binary} | modules])
    after
      0 -> {Enum.reverse(events), Enum.reverse(modules)}
    end
  end

  # Before 1.15 an error is `{file, line, message}`; from 1.15 it is a diagnostic map.
  defp error_file({file, _line, _message}), do: Path.expand(file)
  defp error_file(%{file: file}), do: Path.expand(file)

  defp error_line({_file, line, _message}), do: line || 0
  defp error_line(%{position: {line, _column}}), do: line
  defp error_line(%{position: line}) when is_integer(line), do: line
  defp error_line(%{}), do: 0

  # The compiler's wording differs between versions; the kind it reports does not.
  defp error_kind({_file, _line, message}), do: error_kind(message)
  defp error_kind(%{message: message}), do: error_kind(message)

  defp error_kind(message) do
    cond do
      # From 1.15 a module's errors are each reported, then summarised in one more that names no position.
      message =~ "errors have been logged" -> :logged
      match = Regex.run(~r/undefined function (\S+)\/(\d+)/, message) -> ["undefined_function" | tl(match)]
      match = Regex.run(~r/type (\S+)\/(\d+) undefined/, message) -> ["undefined_type" | tl(match)]
      match = Regex.run(~r/module (\S+) is not loaded/, message) -> ["module_not_available" | tl(match)]
      true -> raise "unclassified compiler error: " <> message
    end
  end

  defp event_line({file, module, aliases, event}, path, nodes) do
    meta = elem(event, 1)

    with line when is_integer(line) <- meta[:line],
         column when is_integer(column) <- meta[:column] do
      path = path.(file)
      named = Map.get(Map.fetch!(nodes, file), {line, column}, [])

      for {naming, [type | fields]} <- event_facts(event, module),
          Enum.any?(named, &names?(&1, naming, module, aliases)) do
        {path, line, column, fields([type, "#{path}:#{line}:#{column}" | fields])}
      end
    else
      _ -> []
    end
  end

  defp event_facts({:alias_reference, _, alias}, _module), do: [{{:alias, alias}, ["alias", inspect(alias)]}]

  defp event_facts({:imported_quoted, _, module, name, arities}, _module) do
    for arity <- arities, do: {{:name, name}, ref(:imported_quoted, module, name, arity)}
  end

  defp event_facts({kind, _, name, arity}, module) when kind in [:local_function, :local_macro] do
    [{{:name, name}, ref(kind, module, name, arity)}]
  end

  defp event_facts({kind, _, module, name, arity}, _module), do: [{{:name, name}, ref(kind, module, name, arity)}]

  defp ref(kind, module, name, arity), do: ["ref", "#{kind}", inspect(module), "#{name}", "#{arity}"]

  # The nodes the parser placed at each {line, column}, as what each names: a call's name, at the call and at its dot,
  # and a capture's call at its `&`; an alias's segments.
  defp nodes(file) do
    {:ok, ast} = Code.string_to_quoted(File.read!(file), columns: true, file: file)

    {_, nodes} =
      Macro.prewalk(ast, %{}, fn node, nodes ->
        nodes =
          Enum.reduce(naming(node), nodes, fn {at, naming}, nodes ->
            Map.update(nodes, at, [naming], &[naming | &1])
          end)

        {node, nodes}
      end)

    nodes
  end

  defp naming({:__aliases__, meta, segments}), do: at(meta, {:aliases, segments})
  defp naming({:&, meta, [{:/, _, [call, _arity]}]}), do: at(meta, {:name, call_name(call)})
  defp naming({:&, meta, [call]}) when is_tuple(call), do: at(meta, {:name, call_name(call)})

  defp naming({{:., dot_meta, [_, name]}, meta, _}) when is_atom(name) do
    at(meta, {:name, name}) ++ at(dot_meta, {:name, name})
  end

  defp naming({name, meta, _}) when is_atom(name), do: at(meta, {:name, name})
  defp naming(_), do: []

  defp at(meta, naming) when is_list(meta) do
    case {meta[:line], meta[:column]} do
      {line, column} when is_integer(line) and is_integer(column) -> [{{line, column}, naming}]
      _ -> []
    end
  end

  defp at(_, _), do: []

  defp call_name({{:., _, [_, name]}, _, _}), do: name
  defp call_name({name, _, _}), do: name
  defp call_name(_), do: nil

  defp names?({:name, name}, {:name, name}, _module, _aliases), do: true

  defp names?({:aliases, [{:__MODULE__, _, _} | others]}, {:alias, alias}, module, _aliases) when is_atom(module) do
    Module.concat([module | others]) == alias
  end

  defp names?({:aliases, [first | others]}, {:alias, alias}, _module, aliases) when is_atom(first) do
    first = Module.concat([first])
    Module.concat([Keyword.get(aliases, first, first) | others]) == alias
  end

  defp names?(_, _, _, _), do: false

  # A field holding a tab or newline would make its line unparseable.
  defp fields(fields) do
    for field <- fields, String.contains?(field, ["\t", "\n"]) do
      raise "a fact's field holds a tab or newline: #{inspect(field)}"
    end

    Enum.join(fields, "\t")
  end

  defp definition_lines({_file, module, binary}, nodes) do
    {:ok, {^module, [debug_info: {:debug_info_v1, backend, data}]}} = :beam_lib.chunks(binary, [:debug_info])
    {:ok, %{definitions: definitions, file: file}} = backend.debug_info(:elixir_v1, module, data, [])

    for {{name, arity}, kind, meta, _clauses} <- definitions, is_map_key(nodes, file) do
      fields = ["def", inspect(module), "#{kind}", "#{name}", "#{arity}", "#{meta[:line]}"]
      {{inspect(module), meta[:line], name, arity}, fields(fields)}
    end
  end
end

CompilerFacts.run(System.argv())
# A test helper's `ExUnit.start/1` would otherwise run the tests as the script exits.
System.halt(0)
