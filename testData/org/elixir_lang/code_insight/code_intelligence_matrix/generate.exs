      # Only `snoc/2` exists, so a call at any other arity has exactly one candidate and none of them match it.
      "x_arity_absent" => %{
        modules: [[snoc_2]],
        calls:
          one_calls ++
            [
              {"no_arguments", 0, "snoc", 0, :no_arguments},
              {"arity_1", 0, "snoc", 1, :qualified},
              {"arity_3", 0, "snoc", 3, :qualified},
              {"aliased_arity_1", 0, "snoc", 1, :aliased},
              {"unqualified_arity_1", 0, "snoc", 1, :unqualified},
              # A name no module declares at any arity, so that "the arity is wrong" has a control to be told apart
              # from "there is no such function". Without it a three-valued diagnostic assertion has an unreachable
