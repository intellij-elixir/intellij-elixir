  def run do
    {:ok, _} = Matrix.Events.start_link()
    Code.put_compiler_option(:tracers, [Matrix.Tracer])
    Code.put_compiler_option(:parser_options, columns: true)

    # The tree is laid out as a Mix project so it can be opened in a sandbox IDE and used by `testUI`: `lib` is what
    # Mix compiles, `_build` is where it expects a dependency's beams, and `spec` holds what is neither - the Erlang
    # sources and the Elixir renderings of them the tests quote.
    for dir <- @generated_directories, do: File.rm_rf!(dir)

    provenance()
    sdk()
    File.mkdir_p!(Path.dirname(@moduledoc_file))
    File.write!(@moduledoc_file, @moduledoc_file_text)

    {scenarios, skipped} =
      for backing <- backings(), form <- forms(), {world, spec} <- Enum.sort(worlds()), reduce: {[], []} do
        {scenarios, skipped} ->
          case not_applicable(backing, form, world) do
            nil -> {[if(form[:attribute], do: attribute_scenario(backing, form, world), else: scenario(backing, form, world, spec)) | scenarios], skipped}
            reason -> {scenarios, [%{"backing" => backing.id, "form" => form.id, "world" => world, "reason" => reason} | skipped]}
          end
      end

    # Which call binds to which definition is the compiler's answer, recorded here rather than asked again at test
    # time, so the pair that answered is part of the oracle: a committed answer from another Elixir is not evidence.
    oracle = %{
      "header" => @header,
      "elixir" => System.version(),
      "otp" => List.to_string(:erlang.system_info(:otp_release)),
      "scenarios" => Enum.reverse(scenarios),
      "notApplicable" => Enum.reverse(skipped)
    }

    File.write!("oracle.json", [:json.format(json(oracle)), ?\n])
    File.write!("manifest.json", [:json.format(manifest(Enum.reverse(scenarios))), ?\n])
  end

  defp json(nil), do: :null
  defp json(map) when is_map(map), do: Map.new(map, fn {key, value} -> {key, json(value)} end)
  defp json(list) when is_list(list), do: Enum.map(list, &json/1)
  defp json(other), do: other

  # The worlds with several arities of one name, which is where an import that names an arity can be told apart
  # from one that takes the whole name: `x_defaults` and `x_defaults_head` declare them with defaults, so one
  # definition covers the arity an `only:` keeps and the one it leaves out.
  @import_worlds ["w2", "x_defaults", "x_defaults_head", "x_arity_separate", "x_use_injected" | @use_parens_worlds]

  # A private definition's remote calls: at the arity it declares and at fewer and more arguments than that. The compiler reads both as
  # "undefined or private", and names no private arity - so neither may the editor.
  @private_remote_worlds ["x_arity_absent"]
  @private_remote_calls [
    {"private_remote", 0, "snoc", 2, :qualified},
    {"private_remote_arity_1", 0, "snoc", 1, :qualified},
    {"private_remote_arity_3", 0, "snoc", 3, :qualified}
  ]

  defp scenario(backing, form, world, spec) do
    spec = spec |> asked(form, world) |> scope(backing, form, world)
    # A second user never calls a private function it is injected with, so the compiler drops it from its `.beam`: a
    # private form asks the one user that does.
    spec = if form[:private] && world in @injecting_worlds, do: %{spec | modules: Enum.take(spec.modules, 1)}, else: spec
    names = module_names(backing, form, world, length(spec.modules))
    worlds_modules = Enum.map(spec.modules, &shape(&1, form))
    primary = worlds_modules |> hd() |> hd()
    prefix = "#{backing.id}_#{form.id}_#{world}_"

    # The modules a `use` world's main module uses, compiled before it; the form then says what its users inject.
    {form, supports} =
      if world in @injecting_worlds,
        do: use_supports(backing, form, world, hd(names), prefix, hd(worlds_modules)),
        else: {form, []}

    modules =
      worlds_modules
      |> Enum.zip(names)
      |> Enum.with_index()
      |> Enum.flat_map(fn {{definitions, module}, index} ->
        compile_module(backing, form, world, module, definitions, if(index == 0, do: primary))
      end)
      |> Kernel.++(supports)

    calls =
      cond do
        form[:private] && world in @private_remote_worlds ->
          @private_remote_calls

        form[:private] ->
          []

        true ->
          Enum.reject(spec.calls, fn {_, _, _, _, shape} ->
            (form[:macro] && shape in [:capture, :apply, :apply_quoted, :mfa]) ||
              (backing.language == :erlang && shape in [:aliased, :aliased_as])
          end)
      end
    # A call at an arity nothing defines cannot share a file with the rest: made locally it is a compile error, so
    # it would take the whole module down with it. It gets its own caller, compiled expecting to fail, and what the
    # compiler says about it is the oracle for what the IDE should say.
    # From another module a private definition is not there at any arity, so the compiler rejects each of these.
    {calls, broken} = if form[:private], do: {[], calls}, else: Enum.split_with(calls, &defined?(&1, worlds_modules))

    caller_path = Path.join(["lib", "callers", backing.id, form.id, Macro.underscore(world) <> ".ex"])
    caller = render_caller(backing, form, world, names, calls) <> atom_modules(spec, prefix)
    File.mkdir_p!(Path.dirname(caller_path))
    File.write!(caller_path, caller)
    caller_events = compile_elixir(caller_path, caller)

    {broken_paths, broken_sites} = broken_caller(backing, form, world, names, broken)
    # Nothing of a private definition is callable from outside, which is what an empty `visible` says.
    broken_sites = if form[:private], do: Enum.map(broken_sites, &Map.put(&1, "visible", [])), else: broken_sites

    {import_paths, import_sites} =
      cond do
        world in @import_worlds -> import_callers(backing, form, world, names, elem(primary, 0))
        world in @import_block_worlds -> import_block_callers(backing, form, world, names, elem(primary, 0))
        world in @compile_time_call_worlds -> compile_time_callers(backing, form, world, elem(primary, 0))
        true -> {[], []}
      end

    {use_paths, use_sites} =
      if world in @use_worlds ++ @use_parens_worlds and !form[:private],
        do: use_callers(backing, form, world, names, prefix),
        else: {[], []}

    import_paths = import_paths ++ use_paths
    import_sites = import_sites ++ use_sites

    %{
      "backing" => backing.id,
      "form" => form.id,
      "world" => world,
      "caller" => caller_path,
      "brokenCallers" => broken_paths,
      "importCallers" => import_paths,
      "modules" => Enum.map(modules, &Map.delete(&1, :local)),
      "sites" =>
        caller_sites(caller_path, caller, caller_events, calls, backing, names) ++
          Enum.flat_map(modules, & &1.local) ++ broken_sites ++ import_sites
    }
    |> then(&if(asks = spec[:asks], do: Map.put(&1, "asks", asks), else: &1))
  end

  defp asked(spec, %{eex: true}, world) when world in @wrapper_worlds,
    do: Map.merge(spec, %{calls: [], asks: ["local", "local_forward"]})

  defp asked(spec, _form, _world), do: spec

  defp atom_modules(spec, prefix),
    do: spec |> Map.get(:atom_modules, []) |> Enum.map_join(&"\ndefmodule #{atom_module(prefix, &1)} do end\n")

  defp atom_module(prefix, {:quoted, name}), do: ~s(:"#{prefix}#{name}")
  defp atom_module(prefix, name), do: ":#{prefix}#{name}"

  # How a caller comes to be able to write `snoc(...)` bare, or not. Each is `{id, directive, calls}`, where the
  # directive is rendered against the declaring module and a call is `{site id, arity}`; which calls compile, and so
  # which name/arities each directive makes visible, is the compiler's answer rather than this table's.
  #
  # `import_transitive` imports a module that itself imports the declaring one: an import is lexical and is not
  # passed on, so nothing reaches the caller. `require_only` makes macros callable qualified but imports nothing.
  defp import_variants(reference, name, %{private: true}) do
    [
      # Nothing private is imported, by any directive.
      {"import_whole", "import #{reference}", [{"import_whole", 2}]},
      {"import_functions", "import #{reference}, only: :functions", [{"import_functions", 2}]},
      # An `only:` key naming a private function is not an empty import: the compiler rejects the directive itself,
      # so the key, not a call, is what it complains about.
      {"import_only_private", "import #{reference}, only: [#{name}: 1]", []}
    ]
  end

  defp import_variants(reference, name, _form) do
    [
      # The selector forms of `only:`: a function is imported by `:functions` and not `:macros`, a macro the other way.
      {"import_functions", "import #{reference}, only: :functions", [{"import_functions", 2}]},
      {"import_macros", "import #{reference}, only: :macros", [{"import_macros", 2}]},
      {"import_only", "import #{reference}, only: [#{name}: 1]", [{"import_only_1", 1}, {"import_only_2", 2}]},
      {"import_except", "import #{reference}, except: [#{name}: 1]", [{"import_except_2", 2}, {"import_except_1", 1}]},
      # A selector and an `except:` together, both ways round: Elixir applies both, whichever is written last.
      {"import_functions_except", "import #{reference}, only: :functions, except: [#{name}: 1]",
       [{"import_functions_except_2", 2}, {"import_functions_except_1", 1}]},
      {"import_except_functions", "import #{reference}, except: [#{name}: 1], only: :functions",
       [{"import_except_functions_2", 2}, {"import_except_functions_1", 1}]},
      {"import_transitive", {:transitive, "import #{reference}"}, [{"import_transitive", 2}]},
      {"require_only", "require #{reference}", [{"require_only", 2}]}
    ]
  end

  # The callers of `import_variants/3`: every call that compiles shares one file, a module per directive; every call
  # the compiler rejects gets a file of its own, because the first rejected call ends the compilation that would
  # have reported the next. The `only:`/`except:` key is a site too - it names a function, and renaming that
  # function has to rename it - bound to the name and arity it names.
  defp import_callers(backing, form, world, names, name) do
    reference = reference(backing, hd(names))
    namespace = "Callers.#{Macro.camelize(backing.prefix)}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)}"
    directory = Path.join(["lib", "callers", backing.id, form.id])
    variants = import_variants(reference, name, form)

    probed =
      Enum.map(variants, fn {id, directive, calls} ->
        visible = visible(directive, reference, namespace <> ".Probe" <> Macro.camelize(id))

        {compiling, rejected} =
          Enum.split_with(calls, fn {_site, arity} -> "#{nfc(name)}/#{arity}" in visible end)

        {id, directive, visible, compiling, rejected}
      end)

    ok_path = Path.join(directory, Macro.underscore(world) <> "_imports.ex")

    ok_source =
      probed
      |> Enum.filter(fn {_, _, _, compiling, _} -> compiling != [] end)
      |> Enum.map_join("\n", fn {id, directive, _, compiling, _} ->
        render_import_module(namespace <> "." <> Macro.camelize(id), key_id(id, id), directive, name, compiling)
      end)
      |> then(&"# #{@header}\n#{&1}")

    File.write!(ok_path, ok_source)
    ok_events = compile_elixir(ok_path, ok_source)

    ok_calls =
      for {id, _, visible, compiling, _} <- probed, {site, arity} <- compiling,
          do: {{site, 0, name, arity, :unqualified}, id, visible}

    ok_sites =
      Enum.map(ok_calls, fn {call, _variant, visible} ->
        [site] = caller_sites(ok_path, ok_source, ok_events, [call], backing, names)
        Map.put(site, "visible", visible)
      end)

    key_sites = import_key_sites(ok_path, ok_source, reference, name)

    {rejected_paths, rejected_sites} =
      probed
      |> Enum.flat_map(fn {id, directive, visible, _, rejected} -> Enum.map(rejected, &{id, directive, visible, &1}) end)
      |> Enum.map(fn {id, directive, visible, {site, arity}} ->
        path = Path.join(directory, Macro.underscore(world) <> "_" <> site <> ".ex")
        source = "# #{@header}\n" <> render_import_module(namespace <> "." <> Macro.camelize(site), key_id(id, site), directive, name, [{site, arity}])
        File.write!(path, source)
        diagnostics = compile_expecting_failure(path, source)
        [broken] = broken_sites(path, source, [{site, 0, name, arity, :unqualified}], diagnostics)
        {path, [Map.put(broken, "visible", visible) | import_key_sites(path, source, reference, name)]}
      end)
      |> Enum.unzip()

    {directive_paths, directive_sites} =
      probed
      |> Enum.filter(fn {_, _, _, compiling, rejected} -> compiling == [] and rejected == [] end)
      |> Enum.map(fn {id, directive, _visible, _, _} ->
        path = Path.join(directory, Macro.underscore(world) <> "_" <> id <> ".ex")
        source = "# #{@header}\n" <> render_import_module(namespace <> "." <> Macro.camelize(id), key_id(id, id), directive, name, [])
        File.write!(path, source)
        diagnostics = compile_expecting_failure(path, source)
        {path, Enum.map(import_key_sites(path, source, reference, name), &rejected_key(&1, diagnostics))}
      end)
      |> Enum.unzip()

    {[ok_path | rejected_paths] ++ directive_paths, ok_sites ++ key_sites ++ List.flatten(rejected_sites) ++ List.flatten(directive_sites)}
  end

  # A caller per site of an import block world, each a module importing the declaring one inside the world's block and
  # calling it inside or after the block. What the block leaves visible at the call is read from `__ENV__` at the
  # same place, and a call it leaves nothing for is compiled expecting the compiler to reject it.
  defp import_block_callers(backing, form, world, names, name) do
    reference = reference(backing, hd(names))
    namespace = "Callers.#{Macro.camelize(backing.prefix)}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)}"
    directory = Path.join(["lib", "callers", backing.id, form.id])
    block = Map.fetch!(@import_blocks, world)
    directive = "import #{reference}"

    @import_block_sites
    |> Enum.map(fn "imported_" <> position = site ->
      position = String.to_existing_atom(position)
      probe = namespace <> ".Probe" <> Macro.camelize(site)
      expression = visible_expression(reference)
      # At module level the probe keeps what it read in an attribute, which a function then returns.
      probe_lines =
        import_block_lines(block, position, directive, "@visible " <> expression, {"visible", expression}) ++
          if(elem(block, 0) == :module, do: ["def visible, do: @visible"], else: [])

      visible = probe_visible(render_lines_module(probe, probe_lines), probe)

      call = "#{name}(a, b) # @#{site}"
      lines = import_block_lines(block, position, directive, "def at_#{site}(a, b), do: " <> call, {"at_#{site}(a, b)", call})
      path = Path.join(directory, Macro.underscore(world) <> "_" <> site <> ".ex")
      source = "# #{@header}\n" <> render_lines_module(namespace <> "." <> Macro.camelize(site), lines)
      File.write!(path, source)
      calls = [{site, 0, name, 2, :unqualified}]

      sites =
        if "#{nfc(name)}/2" in visible,
          do: caller_sites(path, source, compile_elixir(path, source), calls, backing, names),
          else: broken_sites(path, source, calls, compile_expecting_failure(path, source))

      {path, Enum.map(sites, &Map.put(&1, "visible", visible))}
    end)
    |> Enum.unzip()
    |> then(fn {paths, sites} -> {paths, Enum.concat(sites)} end)
  end

  # A caller per site of a compile-time call world: a module calling `name/2` at module level, then defining it in
  # the world's form. Every such call is one the compiler rejects, so nothing is callable there.
  defp compile_time_callers(backing, form, world, name) do
    namespace = "Callers.#{Macro.camelize(backing.prefix)}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)}"
    directory = Path.join(["lib", "callers", backing.id, form.id])

    body =
      if form[:macro], do: "quote(do: {unquote(q), unquote(x)})", else: "{q, x}"

    @compile_time_calls
    |> Enum.sort()
    |> Enum.map(fn {site, {before, open, close, after_lines}} ->
      lines = before ++ [open <> "#{name}(1, 2)#{close} # @#{site}"] ++ after_lines ++ ["", "#{form.definer} #{name}(q, x), do: #{body}"]
      path = Path.join(directory, Macro.underscore(world) <> "_" <> site <> ".ex")
      source = "# #{@header}\n" <> render_lines_module(namespace <> "." <> Macro.camelize(site), lines)
      File.write!(path, source)
      sites = broken_sites(path, source, [{site, 0, name, 2, :unqualified}], compile_expecting_failure(path, source))
      # Go To Declaration lands nowhere, not merely on none of the declaring module's heads: the later definition is
      # the caller's own.
      {path, Enum.map(sites, &Map.merge(&1, %{"visible" => [], "targets" => []}))}
    end)
    |> Enum.unzip()
    |> then(fn {paths, sites} -> {paths, Enum.concat(sites)} end)
  end

  # The import block's lines with `statement` (module level) or `{head, expression}` (a function body) inside or after it.
  defp import_block_lines({:module, opening}, position, directive, statement, _body), do: block_lines(opening, directive, statement, position)

  defp import_block_lines({:body, opening}, position, directive, _statement, {head, expression}),
    do: ["def #{head} do" | Enum.map(block_lines(opening, directive, expression, position), &indent/1)] ++ ["end"]

  defp block_lines(opening, directive, line, :inside), do: [opening, indent(directive), indent(line), "end"]
  defp block_lines(opening, directive, line, :after), do: [opening, indent(directive), "end", "", line]

  defp indent(""), do: ""
  defp indent(line), do: "  " <> line

  defp render_lines_module(module, lines), do: "defmodule #{module} do\n" <> Enum.map_join(lines, "\n", &indent/1) <> "\nend\n"

  # An attribute world's module and its sites: every `@limit` in the source that the compiler expanded as `Kernel.@/1`
  # in that module, a write where it has a value and a read where it has none. The source says which is which, and
  # the tracer's event at the same line and column says the compiler treated it as an attribute at all.
  #
  # What each read's value came from, and what is set where it is read, are asked of probes: the same module with
  # every write's value replaced by the write's id, compiled once per branch choice, recording
  # `Module.attributes_in/1` before each read's `def` and at the top of the module, whose built-ins it takes away.
  defp attribute_scenario(backing, form, world) do
    [module] = module_names(backing, form, world, 1)
    path = Path.join(["lib", backing.id, (module |> Macro.underscore() |> String.replace("/", ".")) <> ".ex"])
    choices = Map.fetch!(@attribute_worlds, world)

    write = fn id, value -> "@#{@attribute} #{value} # @#{id}" end
    read = fn id -> "def #{id}, do: @#{@attribute} # @#{id}" end
    source = "# #{@header}\n" <> attribute_source(world, module, hd(choices), write, read, [])
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)

    Matrix.Events.take()
    {_modules, diagnostics} = Code.with_diagnostics(fn -> Code.compile_string(source, path) end)
    events = Matrix.Events.take()
    {undefined, unexpected} = Enum.split_with(diagnostics, &(&1.message =~ ~r/^undefined module attribute @#{@attribute},/))
    unexpected = Enum.reject(unexpected, &(&1.message =~ ~r/^found quoted keyword "else" but the quotes are not required/ and world =~ ~r/else_quoted/))
    if unexpected != [], do: raise("#{path} compiled with diagnostics: #{inspect(unexpected)}")

    expanded = fn line, column ->
      Enum.any?(events, &(&1.kind == :imported_macro and &1.module == Kernel and &1.name == :@ and &1.line == line and &1.column == column and
                            &1.in == Module.concat([module])))
    end

    {_ast, nodes} =
      source
      |> Code.string_to_quoted!(columns: true, emit_warnings: false)
      |> Macro.prewalk([], fn
        {:@, meta, [{@attribute, _, [_value]}]} = node, nodes -> {node, [{:write, meta[:line], meta[:column]} | nodes]}
        {:@, meta, [{@attribute, _, context}]} = node, nodes when is_atom(context) -> {node, [{:read, meta[:line], meta[:column]} | nodes]}
        node, nodes -> {node, nodes}
      end)

    joined = nodes |> Enum.filter(fn {_kind, line, column} -> expanded.(line, column) end) |> Enum.sort_by(&elem(&1, 1))
    lines = String.split(source, "\n")

    marked =
      for {text, line} <- Enum.with_index(lines, 1), [_, id] <- [Regex.run(~r/# @(\w+)$/, text)], into: %{}, do: {line, id}

    if Enum.map(joined, &elem(&1, 1)) != Enum.sort(Map.keys(marked)),
      do: raise("#{path}: the attribute sites the compiler expanded, #{inspect(joined)}, are not the marked lines #{inspect(marked)}")

    probed = attribute_probes(world, module, choices, for({:read, line, _} <- joined, do: Map.fetch!(marked, line)))

    sites =
      Enum.map(joined, fn {kind, line, column} ->
        id = Map.fetch!(marked, line)

        attribute =
          if kind == :write,
            do: %{"write" => true, "declarations" => [id]},
            else: %{"write" => false, "declarations" => probed.declarations[id], "visible" => probed.visible[id]}

        site = %{
          "id" => id,
          "file" => path,
          "line" => line,
          # The name after the `@`, as a call's site is at its name.
          "column" => column + 1,
          "name" => to_string(@attribute),
          "arity" => 0,
          "binding" => nil,
          "attribute" => attribute
        }

        case Enum.find(undefined, &(kind == :read and position_line(&1.position) == line)) do
          nil -> site
          said -> Map.put(site, "diagnostic", %{"severity" => to_string(said.severity), "message" => said.message})
        end
      end)

    %{
      "backing" => backing.id,
      "form" => form.id,
      "world" => world,
      "caller" => path,
      "brokenCallers" => [],
      "importCallers" => [],
      "modules" => [
        %{
          "module" => module,
          "source" => path,
          "spec" => path,
          "heads" => [],
          "complete" => true,
          "beam" => nil,
          "clauseSource" => nil,
          "delegateTo" => nil,
          "delegateAs" => nil,
          "definitions" => [],
          "declarations" => []
        }
      ],
      "sites" => sites
    }
  end

  # For each read, the ids of the writes its value came from and the user attributes set before it, each the union
  # over the world's branch choices. A probe's diagnostics are not asked: its writes no longer use what they bind.
  defp attribute_probes(world, module, choices, reads) do
    results =
      choices
      |> Enum.with_index()
      |> Enum.map(fn {choice, index} ->
        probe = "#{module}.Probe#{index}"
        record = fn key -> ":persistent_term.put({#{inspect(probe)}, #{inspect(key)}}, Module.attributes_in(__MODULE__))" end
        write = fn id, _value -> "@#{@attribute} {:matrix_write, #{inspect(id)}}" end
        read = fn id -> [record.(id), "def #{id}, do: @#{@attribute}"] end
        source = attribute_source(world, probe, choice, write, read, [record.("top")])

        Matrix.Events.take()
        Code.with_diagnostics(fn -> Code.compile_string(source, "probe.ex") end)
        Matrix.Events.take()

        built_in = :persistent_term.get({probe, "top"})

        Map.new(reads, fn id ->
          declarations = case apply(Module.concat([probe]), String.to_atom(id), []) do
            {:matrix_write, write} -> [write]
            nil -> []
          end

          {id, {declarations, Enum.map(:persistent_term.get({probe, id}) -- built_in, &to_string/1)}}
        end)
      end)

    union = fn id, position -> results |> Enum.flat_map(&elem(&1[id], position)) |> Enum.uniq() |> Enum.sort() end

    %{
      declarations: Map.new(reads, &{&1, union.(&1, 0)}),
      visible: Map.new(reads, &{&1, union.(&1, 1)})
    }
  end

  # `write.(id, value)` writes the attribute, `read.(id)` reads it in `def <id>`, and `taken` is the branch choice:
  # `true` in the shipped source, flipped in a probe.
  defp attribute_source("x_attribute_in_dsl", module, choice, write, read, top) do
    dsl = module <> ".Dsl"

    render_lines_module(dsl, ["defmacro block(do: body), do: body"]) <> "\n" <>
      render_lines_module(module, List.flatten(top ++ ["import #{dsl}" | attribute_body("x_attribute_in_dsl", choice, write, read)]))
  end

  defp attribute_source(world, module, choice, write, read, top),
    do: render_lines_module(module, List.flatten(top ++ attribute_body(world, choice, write, read)))

  # The read before any write is undefined, and the compiler says so.
  defp attribute_body("x_attribute", _, w, r), do: [r.("before_write"), w.("write", 1), r.("read")]
  defp attribute_body("x_attribute_redefined", _, w, r), do: [w.("first", 1), r.("read_first"), w.("second", 100), r.("read_second")]
  defp attribute_body("x_attribute_in_if", taken, w, r), do: ["if #{loaded(taken)} do", "  " <> w.("in_if", 1), "else", "  " <> w.("in_else", 2), "end", r.("read")]

  defp attribute_body("x_attribute_in_case", taken, w, r),
    do: ["case #{loaded(taken)} do", "  true -> " <> w.("in_true", 3), "  _ -> " <> w.("in_other", 4), "end", r.("read")]

  defp attribute_body("x_attribute_in_for", taken, w, r),
    do: [w.("before_for", 5), "for x <- #{if taken, do: "[6]", else: "[]"}, do: " <> w.("in_for", "x"), r.("read")]

  defp attribute_body("x_attribute_in_try", taken, w, r),
    do: ["try do", "  " <> if(taken, do: ":ok", else: ~s(raise "not taken")), "  " <> w.("in_try", 7), "rescue", "  _ -> " <> w.("in_rescue", 8), "end", r.("read")]

  defp attribute_body("x_attribute_in_with", taken, w, r), do: [w.("before_with", 9), "with true <- #{loaded(taken)}, do: " <> w.("in_with", 10), r.("read")]
  defp attribute_body("x_attribute_in_dsl", _, w, r), do: ["block do", "  " <> w.("in_block", 11), "end", r.("read")]

  # A keyword value, which runs when the condition fails, so `taken` fails it.
  defp attribute_body("x_attribute_in_else_" <> shape, taken, w, r) do
    {key, open, close} =
      case shape do
        "keyword" -> {"else", "(", ")"}
        "quoted" -> {~s("else"), "(", ")"}
        "list" -> {"else", "[", "]"}
      end

    [w.("before_if", 12), "if #{loaded(!taken)}, do: nil, #{key}: #{open}", "  " <> w.("in_else", 13), close, r.("read")]
  end

  defp attribute_body("x_attribute_in_try_after", _, w, r),
    do: [w.("before_try", 14), "try do", "  :ok", "after", "  " <> w.("in_after", 15), "end", r.("read")]

  defp attribute_body("x_attribute_in_rescue", taken, w, r),
    do: [w.("before_try", 16), "try do", "  " <> if(taken, do: ~s(raise "matrix"), else: ":ok"), "rescue", "  _ -> " <> w.("in_rescue", 17), "end", r.("read")]

  defp attribute_body("x_attribute_in_catch", taken, w, r),
    do: [w.("before_try", 18), "try do", "  " <> if(taken, do: "throw :matrix", else: ":ok"), "catch", "  _ -> " <> w.("in_catch", 19), "end", r.("read")]

  defp loaded(true), do: "Code.ensure_loaded?(Kernel)"
  defp loaded(false), do: "Code.ensure_loaded?(Matrix.Absent)"

  # The key of a directive the compiler rejected names nothing it can import: no binding, and what the compiler said.
  defp rejected_key(site, diagnostics) do
    said = Enum.find(diagnostics, &(position_line(&1.position) == site["line"])) ||
      raise "#{site["file"]}:#{site["line"]} holds a rejected directive, but no diagnostic names that line"

    Map.merge(site, %{"binding" => nil, "visible" => [], "diagnostic" => %{"severity" => to_string(said.severity), "message" => said.message}})
  end

  # A module per directive; a transitive one is preceded by the module the directive really sits in, which the
  # caller then imports.
  # Only an `only:`/`except:` directive has a key, marked `<owner>_key` after the site or variant it serves.
  defp key_id(variant, owner) when variant in ["import_only", "import_except", "import_only_private", "import_functions_except", "import_except_functions"],
    do: owner <> "_key"
  defp key_id(_variant, _owner), do: nil

  defp render_import_module(module, _key_id, {:transitive, directive}, name, calls) do
    """
    defmodule #{module}.Middle do
      #{directive}
      def middle_marker, do: :ok
    end

    #{render_import_module(module, nil, "import #{module}.Middle", name, calls)}
    """
  end

  defp render_import_module(module, key_id, directive, name, calls) do
    key = if key_id, do: " # @#{key_id}", else: ""

    body =
      Enum.map_join(calls, "\n", fn {site, arity} ->
        call = "#{name}(#{arguments(arity)})"
        parameters = Enum.map_join(["a", "b"], ", ", fn parameter -> if(call =~ ~r/\b#{parameter}\b/, do: parameter, else: "_" <> parameter) end)
        "  def at_#{site}(#{parameters}), do: #{call} # @#{site}"
      end)

    """
    defmodule #{module} do
      #{directive}#{key}

    #{body}
    end
    """
  end

  # The name/arities of the declaring module a directive makes callable bare, as Elixir's own environment has them:
  # a probe module with nothing but the directive reads them from `__ENV__` and is never written to disk.
  defp visible(directive, reference, probe) do
    {middle, directive} =
      case directive do
        {:transitive, inner} -> {"defmodule #{probe}.Middle do\n  #{inner}\nend\n", "import #{probe}.Middle"}
        directive -> {"", directive}
      end

    source = """
    #{middle}defmodule #{probe} do
      #{directive}
      @visible #{visible_expression(reference)}
      def visible, do: @visible
    end
    """

    probe_visible(source, probe)
  end

  defp visible_expression(reference),
    do: ~s[for {module, pairs} <- __ENV__.functions ++ __ENV__.macros, module == #{reference}, {name, arity} <- pairs, do: "\#{name}/\#{arity}"]

  defp probe_visible(source, probe) do
    Matrix.Events.take()
    # A probe whose directive is unused would warn about it, and that is not what it is asking.
    {compiled, _diagnostics} =
      Code.with_diagnostics(fn ->
        try do
          Code.compile_string(source, "probe.ex")
        rescue
          # A directive the compiler rejects makes nothing visible.
          _ -> nil
        end
      end)

    Matrix.Events.take()
    visible = if compiled, do: apply(Module.concat([probe]), :visible, []) |> Enum.map(&nfc/1) |> Enum.sort(), else: []
    :code.purge(Module.concat([probe]))
    :code.delete(Module.concat([probe]))
    visible
  end

  # The key of an `only:`/`except:` list names one function by name and arity: the site is that name, bound to it.
  defp import_key_sites(path, source, reference, name) do
    for {text, line} <- source |> String.split("\n") |> Enum.with_index(1),
        [_, id] <- [Regex.run(~r/# @(\w+_key)$/, text)] do
      [{start, _}] = Regex.run(~r/\[#{Regex.escape(name)}: 1\]/u, text, return: :index)

      %{
        "id" => id,
        "file" => path,
        "line" => line,
        "column" => utf16_length(binary_part(text, 0, start + 1)) + 1,
        "name" => nfc(name),
        "arity" => 1,
        "binding" => %{"module" => reference, "name" => nfc(name), "arity" => 1, "kind" => "import_key"}
      }
    end
  end

  # The shapes that are not calls of the definition at all, so no arity can be wrong for them.
  @not_calls [:variable, :atom, :keyword, :interpolated_atom, :module_atom]

  # The shapes whose atom names a module the caller declares, where Go To Declaration must land.
  @module_atoms [:interpolated_atom, :module_atom]

  defp defined?({_id, _module, _name, _arity, shape}, _modules) when shape in @not_calls or shape in [:module_defimpl | @module_shapes], do: true

  defp defined?({_id, module, name, arity, _shape}, modules) do
    modules
    |> Enum.at(module, [])
    |> Enum.any?(fn {definition_name, [first | _]} ->
      {parameters, _guard, _head?} = clause_parts(first)
      defaults = Enum.count(parameters, &is_tuple/1)
      # Elixir normalises identifiers, so a decomposed declaration and a precomposed call are the same function.
      nfc(definition_name) == nfc(name) and arity in (length(parameters) - defaults)..length(parameters)
    end)
  end

  # Calling an undefined function locally is a compile error and takes the whole module with it, so the remote calls
  # in the same file would never reach the warning that names them. The two kinds get a file each.
  @imported_shapes [:unqualified, :pipe]

  defp broken_caller(backing, form, world, names, calls) do
    {imported, remote} = Enum.split_with(calls, fn {_, _, _, _, shape} -> shape in @imported_shapes end)

    [{remote_path, remote_sites}, {imported_path, imported_sites}] =
      [{remote, "_broken"}, {imported, "_undefined"}]
      |> Enum.map(fn {subset, suffix} -> broken_caller_file(backing, form, world, names, subset, suffix) end)

    {Enum.reject([remote_path, imported_path], &is_nil/1), remote_sites ++ imported_sites}
  end

  defp broken_caller_file(_backing, _form, _world, _names, [], _suffix), do: {nil, []}

  defp broken_caller_file(backing, form, world, names, calls, suffix) do
    path = Path.join(["lib", "callers", backing.id, form.id, Macro.underscore(world) <> suffix <> ".ex"])
    source = render_caller(backing, form, world <> suffix, names, calls)
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)

    diagnostics = compile_expecting_failure(path, source)
    {path, broken_sites(path, source, calls, diagnostics)}
  end

  # Nothing here is expected to compile, and a local call at an unknown arity is a hard error rather than a warning,
  # so the module may not be produced at all. Only what the compiler said is kept.
  defp compile_expecting_failure(path, source) do
    Matrix.Events.take()

    {_result, diagnostics} =
      Code.with_diagnostics(fn ->
        try do
          Code.compile_string(source, path)
        rescue
          _ -> :error
        end
      end)

    Matrix.Events.take()

    if diagnostics == [], do: raise("#{path} was expected to be rejected by the compiler, and was not")

    diagnostics
  end

  defp broken_sites(path, source, calls, diagnostics) do
    lines = source |> String.split("\n") |> Enum.with_index(1)

    Enum.map(calls, fn {id, _module, name, arity, _shape} ->
      {text, line} = Enum.find(lines, fn {text, _} -> String.ends_with?(text, "# @#{id}") end)
      said = Enum.find(diagnostics, fn diagnostic -> position_line(diagnostic.position) == line end)

      # A site in a file the compiler rejected, with nothing said about its own line, would be committed as a call
      # the compiler was happy with - and the matrix would then assert the IDE must say nothing about it, the exact
      # inverse of what this file exists to test. It happens when the compiler reports at another line, or aborts on
      # an earlier hard error before reaching this call, so the fix is a caller with fewer calls per file.
      if is_nil(said) do
        raise "#{path}:#{line} (@#{id}) is in a file the compiler rejected, but no diagnostic names that line; " <>
                "split the call into its own file so the compiler reaches it"
      end

      %{
        "id" => id,
        "file" => path,
        "line" => line,
        "column" => name_column(text, name),
        "name" => nfc(name),
        "arity" => arity,
        "binding" => nil,
        "diagnostic" => %{"severity" => to_string(said.severity), "message" => said.message}
      }
    end)
  end

  defp position_line({line, _column}), do: line
  defp position_line(line) when is_integer(line), do: line
  defp position_line(_), do: nil

  # Every scenario shares one project, so a function name has to name its scenario. Searching for a bare `snoc`
  # would return every scenario's files and discard all but one, and the search-driven features - Find Usages and
  # Rename, already the most expensive - would pay for it. Module names already carry the scenario (`Src.Def.W1`),
  # so only function names need this. `local_site`, `uses` and `target_marker` are never search targets, so they
  # keep their bare names.
  # Names a call means as Kernel's, which scoping them would turn into just another name nothing declares.
  @kernel_names ["is_nil"]

  defp scope(spec, backing, form, world) do
    prefix = "#{backing.id}_#{form.id}_#{world}_"

    %{
      spec
      | modules:
          Enum.map(spec.modules, fn definitions ->
            Enum.map(definitions, fn {name, clauses} -> {prefix <> name, clauses} end)
          end),
        calls:
          Enum.map(spec.calls, fn {id, module, name, arity, shape} ->
            {id, module, if(name in @kernel_names or shape in @module_shapes, do: name, else: prefix <> name), arity, shape}
          end)
    }
  end

  # A clause is `{parameters, guard}`, or `{parameters, guard, :head}` for the bodiless head Elixir requires when
  # several clauses of one definition share default arguments. Nothing else may carry defaults in that case.
  defp clause_parts({parameters, guard}), do: {parameters, guard, false}
  defp clause_parts({parameters, guard, :head}), do: {parameters, guard, true}

  defp head?(clause), do: clause_parts(clause) |> elem(2)

  # A guard or a delegate has one clause per name and arity, no guard of its own, and so never a separate head.
  defp shape(definitions, form) do
    if form[:guard] || form[:delegate] do
      Enum.map(definitions, fn {name, [clause | _]} ->
        {parameters, _guard, _head?} = clause_parts(clause)
        {name, [{parameters, nil}]}
      end)
    else
      definitions
    end
  end

  defp module_names(%{language: :elixir, prefix: prefix}, form, world, count) do
    main = "#{prefix}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)}"
    [main | Enum.map(1..(count - 1)//1, fn _ -> main <> ".Other" end)]
  end

  defp module_names(%{language: :erlang, prefix: prefix}, form, world, count) do
    main = "#{prefix}_#{form.id}_#{world}"
    [main | Enum.map(1..(count - 1)//1, fn _ -> main <> "_other" end)]
  end

  defp reference(%{language: :elixir}, module), do: module
  defp reference(%{language: :erlang}, module), do: ":" <> module

  # The modules a `use` world's main module uses, compiled before it, and the form its users are compiled with.
  #
  # `Injector.__using__` quotes the world's definitions: in `x_use_injected` beside a nested `use Inner` (whose quote
  # defines `chained/1`), an `import Helpers` and a private `hidden/1`, so the callers can ask which of them an `import`
  # of the user brings in; in `x_use_apply` as `Injector.view/0`, which `__using__` reaches through `apply`. `DefUsing`
  # (a `def __using__`) and `PrivateUsing` (a `defmacrop __using__`) are what `use` cannot call: neither injects anything.
  # A macro's quote is `unquote: false`, so the macro's own `quote`/`unquote` inside it is written as it would be in a
  # module; every other form's is the plain `quote do` most `__using__`s are written with.
  defp use_supports(backing, form, world, main, prefix, definitions) do
    style =
      cond do
        world == "x_use_apply" -> :apply
        world in @use_parens_worlds -> :parens
        true -> :macro
      end

    quote = if form[:macro] && !form[:guard], do: "quote unquote: false", else: "quote"
    parens = style == :parens or match?({_, _, :list}, Map.get(@use_quote_wrappers, world))
    clauses = form |> Map.merge(%{wrapper: nil, unquote_name: false, branches: false, spec: false, parens: parens}) |> render_clauses(definitions)
    clauses = wrap(clauses, Map.get(@use_quote_wrappers, world))
    quoted = clauses |> Enum.map_join("\n", &String.replace(&1, ~r/^/m, if(style == :parens, do: "  ", else: "    ")))
    module = fn suffix -> main <> "." <> suffix end

    extras =
      if style in [:macro, :parens],
        do: [{prefix <> "chained", [{["x"], nil}]}, {prefix <> "hidden", [{["x"], nil}]}],
        else: []

    sources =
      case style do
        :macro ->
          [
            {"Helpers", [{prefix <> "helper", [{["x"], nil}]}], "  def #{prefix}helper(x), do: x"},
            {"Inner", [],
             "  defmacro __using__(_) do\n    quote do\n      def #{prefix}chained(x), do: x\n    end\n  end"},
            {"Injector", [],
             """
               defmacro __using__(_) do
                 #{quote} do
                   use #{module.("Inner")}
                   import #{module.("Helpers")}, warn: false
                   defp #{prefix}hidden(x), do: x
             #{quoted}
                 end
               end\
             """},
            {"DefUsing", [],
             "  def __using__(_) do\n    quote do\n      def #{prefix}not_injected(x), do: x\n    end\n  end"},
            {"PrivateUsing", [],
             "  defmacrop __using__(_) do\n    quote do\n      def #{prefix}privately_injected(x), do: x\n    end\n  end"}
          ]

        # Each statement on a line of its own: `declarations/1` reads one definition per line. Several statements in a
        # keyword `do:` are a parenthesised block.
        :parens ->
          quote = if form[:macro] && !form[:guard], do: "quote(unquote: false, do: (", else: "quote(do: ("

          [
            {"Helpers", [{prefix <> "helper", [{["x"], nil}]}], "  def(#{prefix}helper(x), do: x)"},
            {"Inner", [], "  defmacro(__using__(_), do: quote(do:\n    def(#{prefix}chained(x), do: x)\n  ))"},
            {"Injector", [],
             """
               defmacro(__using__(_), do: #{quote}
                 use(#{module.("Inner")})
                 import(#{module.("Helpers")}, warn: false)
                 defp(#{prefix}hidden(x), do: x)
             #{quoted}
               )))\
             """},
            {"DefUsing", [], "  def(__using__(_), do: quote(do:\n    def(#{prefix}not_injected(x), do: x)\n  ))"},
            {"PrivateUsing", [], "  defmacrop(__using__(_), do: quote(do:\n    def(#{prefix}privately_injected(x), do: x)\n  ))"}
          ]

        :apply ->
          [
            {"Injector", [],
             """
               defmacro __using__(which) when is_atom(which), do: apply(__MODULE__, which, [])

               def view do
                 #{quote} do
             #{quoted}
                 end
               end

               defp secret do
                 quote do
                   def #{prefix}secret(x), do: x
                 end
               end\
             """}
          ]
      end

    supports =
      Enum.map(sources, fn {suffix, declared, body} ->
        name = module.(suffix)
        # `target_marker/0` is what the fixture guard reads a module through when nothing of the world's own survives in
        # its `.beam`: a `defmacrop __using__` is expanded away.
        source = "# #{@header}\ndefmodule #{name} do\n#{body}\n\n  def target_marker, do: :ok\nend\n"
        compile_one(backing, %{id: "def", definer: "def", written: source}, world, name, declared, nil, nil)
      end)

    # The quotes' declarations, as the users' own: each written in the quote's file.
    written = Enum.filter(supports, &(&1["module"] in [module.("Injector"), module.("Inner")]))
    names = MapSet.new(definitions ++ extras, fn {name, _} -> nfc(name) end)

    declarations =
      for support <- written, declaration <- support["declarations"], MapSet.member?(names, declaration["name"]),
          do: Map.put(declaration, "file", support["source"])

    heads = for support <- written, head <- heads(support["source"]), MapSet.member?(names, head["name"]), do: head

    use = %{
      injector: module.("Injector"),
      argument: if(style == :apply, do: ", :view", else: ""),
      extras: extras,
      declarations: declarations,
      heads: heads,
      module: nil
    }

    {Map.put(form, :use, use), supports}
  end

  # What a user defines beyond the world's own definitions: what the nested `use` and the quote's private function add.
  defp injected(%{use: %{extras: extras}}, :definitions), do: extras
  defp injected(_form, :definitions), do: []

  # The callers asking what an `import` of a `use`r brings in, and what a `use` that cannot inject leaves undefined.
  # Every call the compiler accepts shares one file; each it rejects gets its own, as the first rejection ends the
  # compilation that would report the next.
  defp use_callers(backing, form, world, names, prefix) do
    reference = hd(names)
    namespace = "Callers.#{Macro.camelize(backing.prefix)}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)}"
    directory = Path.join(["lib", "callers", backing.id, form.id])
    snoc = prefix <> "snoc"
    module = fn suffix -> reference <> "." <> suffix end

    {accepted, rejected} =
      case world do
        _ when world in ["x_use_injected" | @use_parens_worlds] ->
          {[
             {"chained", "import #{reference}", prefix <> "chained", 1},
             {"except_chained", "import #{reference}, except: [#{snoc}: 1]", prefix <> "chained", 1}
           ],
           [
             {"only_chained_snoc", "import #{reference}, only: [#{prefix}chained: 1]", snoc, 2},
             {"hidden", "import #{reference}", prefix <> "hidden", 1},
             {"helper", "import #{reference}", prefix <> "helper", 1},
             {"def_using", "use #{module.("DefUsing")}", prefix <> "not_injected", 1},
             {"private_using", "use #{module.("PrivateUsing")}", prefix <> "privately_injected", 1}
           ]}

        "x_use_apply" ->
          {[], [{"use_secret", "use #{module.("Injector")}, :secret", prefix <> "secret", 1}]}

        _ ->
          {[], []}
      end

    render = fn id, directive, name, arity ->
      call = "#{name}(#{arguments(arity)})"
      parameters = Enum.map_join(["a", "b"], ", ", fn parameter -> if(call =~ ~r/\b#{parameter}\b/, do: parameter, else: "_" <> parameter) end)
      "defmodule #{namespace}.#{Macro.camelize(id)} do\n  #{directive}\n\n  def at_#{id}(#{parameters}), do: #{call} # @#{id}\nend\n"
    end

    visible_of = fn id, directive ->
      if String.starts_with?(directive, "import "), do: visible(directive, reference, namespace <> ".Probe" <> Macro.camelize(id))
    end

    {ok_paths, ok_sites} =
      if accepted == [] do
        {[], []}
      else
        path = Path.join(directory, Macro.underscore(world) <> "_uses.ex")
        source = "# #{@header}\n" <> Enum.map_join(accepted, "\n", fn {id, directive, name, arity} -> render.(id, directive, name, arity) end)
        File.write!(path, source)
        events = compile_elixir(path, source)

        sites =
          Enum.map(accepted, fn {id, directive, name, arity} ->
            [site] = caller_sites(path, source, events, [{id, 0, name, arity, :unqualified}], backing, names)
            if directive == "import #{reference}", do: site, else: Map.put(site, "visible", visible_of.(id, directive))
          end)

        {[path], sites}
      end

    {rejected_paths, rejected_sites} =
      rejected
      |> Enum.map(fn {id, directive, name, arity} ->
        path = Path.join(directory, Macro.underscore(world) <> "_" <> id <> ".ex")
        source = "# #{@header}\n" <> render.(id, directive, name, arity)
        File.write!(path, source)
        {id, directive, name, arity, path, source, compile_rejecting(path, source)}
      end)
      |> Enum.map(fn {id, directive, name, arity, path, source, {diagnostics, raised}} ->
        [site] =
          case raised do
            # The `use` itself raised, so the compiler never reached the call: what it said is the call's answer too.
            nil -> broken_sites(path, source, [{id, 0, name, arity, :unqualified}], diagnostics)
            message -> [rejected_call(path, source, id, name, arity, message)]
          end

        {path, if(visible = visible_of.(id, directive), do: Map.put(site, "visible", visible), else: site)}
      end)
      |> Enum.unzip()

    {ok_paths ++ rejected_paths, ok_sites ++ rejected_sites}
  end

  # What the compiler said about a file it rejected, and the message of what it raised where that was an exception
  # rather than a diagnostic - a `use` whose `__using__` cannot be called raises while the module body runs.
  defp compile_rejecting(path, source) do
    Matrix.Events.take()

    {raised, diagnostics} =
      Code.with_diagnostics(fn ->
        try do
          Code.compile_string(source, path)
          nil
        rescue
          error in CompileError -> if(error.description =~ "errors have been logged", do: nil, else: Exception.message(error))
          error -> Exception.message(error)
        end
      end)

    Matrix.Events.take()
    if diagnostics == [] and raised == nil, do: raise("#{path} was expected to be rejected by the compiler, and was not")
    {diagnostics, raised}
  end

  defp rejected_call(path, source, id, name, arity, message) do
    {text, line} = source |> String.split("\n") |> Enum.with_index(1) |> Enum.find(fn {text, _} -> String.ends_with?(text, "# @#{id}") end)

    %{
      "id" => id,
      "file" => path,
      "line" => line,
      "column" => name_column(text, name),
      "name" => nfc(name),
      "arity" => arity,
      "binding" => nil,
      "diagnostic" => %{"severity" => "error", "message" => message}
    }
  end

  # The declaring module, and for a delegate whose target exists, the target module compiled before it.
  defp compile_module(backing, form, world, module, definitions, primary) do
    {target, targets} =
      case form[:delegate] do
        nil -> {nil, []}
        :missing -> {module <> ".Missing", []}

        :imports ->
          source = module <> ".Source"
          target = module <> ".Target"
          imported = strip_defaults(definitions)

          {target,
           [
             compile_one(backing, %{id: "def", definer: "def"}, world, source, imported, nil, nil),
             compile_one(backing, %{id: "def", definer: "def", imports: {source, imported}}, world, target, [], nil, nil)
           ]}
        :same -> {module <> ".Target", [compile_one(backing, %{id: "def", definer: "def"}, world, module <> ".Target", (strip_defaults(definitions) ++ target_extras(world, definitions)) |> delegated_names(form), nil, nil)]}
        :compiled -> {module <> ".Target", [compile_one(@delegate_target_backing, %{id: "def", definer: "def"}, world, module <> ".Target", strip_defaults(definitions) ++ target_extras(world, definitions), nil, nil)]}
      end

    [compile_one(backing, form, world, module, definitions, primary, target) | targets]
  end

  # Where the calls are at arities the delegate does not declare, its target does define them: a delegate forwards
  # only the arities it names, so the target having more must not make those calls resolve.
  defp target_extras("x_arity_absent", [{name, _} | _]), do: [{name, [{["q"], nil}]}, {name, [{["q", "x", "y"], nil}]}]
  defp target_extras(_world, _definitions), do: []

  # What the target calls each function, where the delegate names it with `as:`.
  defp delegated_names(definitions, %{as: prefix}), do: Enum.map(definitions, fn {name, clauses} -> {prefix <> name, clauses} end)
  defp delegated_names(definitions, _form), do: definitions

  # A delegate target takes the same arities without the defaults, so a bodiless head has nothing left to declare.
  defp strip_defaults(definitions) do
    Enum.map(definitions, fn {name, clauses} ->
      bare =
        clauses
        |> Enum.reject(&head?/1)
        |> Enum.map(fn clause ->
          {parameters, guard, _head?} = clause_parts(clause)
          {Enum.map(parameters, fn {parameter, _} -> parameter; parameter -> parameter end), guard}
        end)

      {name, bare}
    end)
  end

  defp compile_one(backing, form, world, module, definitions, primary, target) do
    form =
      Map.merge(form, %{
        wrapper: Map.get(@wrappers, world) || Map.get(@use_wrappers, world),
        parens: world in @list_wrapper_worlds,
        unquote_name: world == "x_unquote_name",
        branches: world == "x_if_else",
        spec: primary != nil and backing.id == "src" and world in @spec_worlds and form.id in @function_forms,
        local_forward: primary != nil and backing.id == "src" and world in @local_forward_worlds and form.id in @function_forms,
        moduledoc: primary != nil && Map.get(@moduledocs, world),
        protocol: primary != nil and world in @protocol_worlds
      })
    extension = if(backing.language == :elixir, do: ".ex", else: ".erl")
    # Named after the whole module: every world's delegate target is a `Target`.
    file = if(backing.language == :elixir, do: module |> Macro.underscore() |> String.replace("/", "."), else: module)
    # Erlang sources sit outside `lib`, which is Mix's to compile and holds Elixir only.
    root = if(backing.language == :elixir, do: "lib", else: "spec")
    path = Path.join([root, backing.id, file <> extension])
    source = render_source(backing, form, module, definitions, primary, target)
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)

    {beam, events, binary} = compile_source(backing, module, path, source)

    spec =
      if backing.language == :erlang do
        spec_path = path <> ".ex.spec"
        File.write!(spec_path, render_elixir(form, ":" <> module, definitions, nil, nil))
        spec_path
      else
        path
      end

    local =
      if primary,
        do:
          if(form[:protocol], do: [], else: local_sites(path, source, events, backing, module, primary, local_arity(definitions, primary))) ++
            marked_sites(path, source, events, backing, module) ++ if(form[:moduledoc], do: module_sites(path, source, events, binary), else: []),
        else: []

    %{
      "module" => reference(backing, module),
      "source" => path,
      "spec" => spec,
      "heads" => artefact_heads(if(form[:use] && form.use.module == nil, do: form.use.heads, else: heads(spec)), beam),
      "complete" => complete?(beam),
      "beam" => beam,
      "clauseSource" => Map.get(backing, :clause_source),
      "delegateTo" => target,
      # The prefix `as:` gives the target's function names, absent where the delegate keeps the head's name.
      "delegateAs" => form[:as],
      # Under `if`/`else` only the `if`'s definition is compiled, and so only it is defined.
      "definitions" =>
        Enum.map(if(form[:branches], do: Enum.take(definitions, 1), else: definitions) ++ injected(form, :definitions), &definition/1),
      "declarations" =>
        cond do
          # A user of a `use` declares nothing itself: what it defines is written in the quotes it uses.
          form[:use] && form.use.module == nil -> form.use.declarations
          backing.language == :elixir -> declarations(source)
          true -> []
        end,
      local: local
    }
    |> then(&if(form[:moduledoc], do: Map.put(&1, "moduledoc", moduledoc(binary, source)), else: &1))
    |> then(fn record ->
      docs = if form[:delegate], do: function_docs(binary), else: []
      if docs == [], do: record, else: Map.put(record, "docs", docs)
    end)
  end

  # Each function `Code.fetch_docs/1` has a doc for. A `defdelegate` without an `@doc` of its own has none there, only
  # `delegate_to` metadata: the compiler does not copy the target's doc, so a delegate absent from this list has none.
  defp function_docs(binary) do
    {:ok, {_module, [{~c"Docs", chunk}]}} = :beam_lib.chunks(binary, [~c"Docs"])
    {:docs_v1, _anno, _language, _format, _doc, _metadata, docs} = :erlang.binary_to_term(chunk)

    for {{:function, name, arity}, _anno, _signature, %{"en" => doc}, _metadata} <- docs,
        do: %{"name" => nfc(Atom.to_string(name)), "arity" => arity, "doc" => doc}
  end

  # What `Code.fetch_docs/1` says of the module's documentation: its text, or that it is hidden. `written` is every
  # text a `@moduledoc` in the source spells, which a hidden doc, or one set later, must not show.
  defp moduledoc(binary, source) do
    {:ok, {_module, [{~c"Docs", chunk}]}} = :beam_lib.chunks(binary, [~c"Docs"])
    {:docs_v1, _anno, _language, _format, doc, _metadata, _docs} = :erlang.binary_to_term(chunk)

    {_ast, written} =
      source
      |> Code.string_to_quoted!()
      |> Macro.prewalk([], fn
        {:@, _, [{:moduledoc, _, [text]}]} = node, acc when is_binary(text) -> {node, [text | acc]}
        node, acc -> {node, acc}
      end)

    %{
      "doc" => if(is_map(doc), do: Map.fetch!(doc, "en")),
      "hidden" => doc == :hidden,
      "written" => Enum.reverse(written)
    }
  end

  # The arities come from the first clause, which is the bodiless head where there is one, because that is where the
  # defaults are declared. A head is not itself a clause, so it is not counted as one.
  defp definition({name, [first | _] = clauses}) do
    {parameters, _guard, _head?} = clause_parts(first)
    defaults = Enum.count(parameters, &is_tuple/1)
    bodied = Enum.reject(clauses, &head?/1)

    %{
      "name" => nfc(name),
      "minArity" => length(parameters) - defaults,
      "maxArity" => length(parameters),
      "clauses" => length(bodied)
    }
  end

  # The standard library modules a form declares functions through, as the pinned Elixir compiled them: a real
  # project always has them, compiled, in its SDK, and the plugin only knows `EEx.function_from_string` declares
  # something once `EEx` resolves. Copied rather than referenced so every CI leg attaches the same bytes. `Kernel` and
  # `Kernel.SpecialForms` are every module's implicit imports: without them `apply/3` and `quote` resolve to nothing, and
  # a diagnostic at a call inside `apply(...)` reads the editor's complaint about `apply` itself.
  @sdk_modules [EEx, Mix.Generator, Kernel, Kernel.SpecialForms]

  defp sdk do
    directory = Path.join(["_build", "dev", "lib", "elixir_sdk", "ebin"])
    File.mkdir_p!(directory)

    for module <- @sdk_modules do
      {:module, ^module} = Code.ensure_loaded(module)
      File.cp!(:code.which(module), Path.join(directory, "#{module}.beam"))
    end
  end

  # The oldest pair CI supports, from `.github/ci-versions.json`'s `beam.additional`.
  @oldest_elixir "1.11.4-otp-24"
  @oldest_otp "24.3.4.6"

  @doc """
  One module compiled by the oldest Elixir CI supports as well as by the pinned one.

  Measured before building it: what the decompiler reads - definitions, their kinds, parameter names, clause counts
  and the docs metadata carrying `defaults` and `delegate_to` - is byte-identical across 1.11.4 and 1.20.4 for every
  construct this matrix uses. The versions differ only in `Dbgi` map keys the plugin never reads (`line` became
  `anno`, `is_behaviour` became `defines_behaviour`). So provenance is a guard, not a backing: a whole axis would
  have cost thousands of cells that cannot disagree. What the guard still catches is a reader tuned for modern beams
  that stops reading old dependencies - a plausible outcome of the migration this matrix exists to protect.
  """
  def provenance do
    File.mkdir_p!("provenance")
    source = Path.join("provenance", "provenance.ex")
    File.write!(source, provenance_source())

    for {elixir, otp} <- [{@oldest_elixir, @oldest_otp}, {System.version(), nil}] do
      directory = Path.join("provenance", elixir |> String.split("-") |> hd())
      File.mkdir_p!(directory)
      compile_provenance(source, directory, elixir, otp)
    end
  end

  # The pinned Elixir is this script's own; anything else needs mise to put it on PATH.
  defp compile_provenance(source, directory, _elixir, nil) do
    for {module, binary} <- Code.compile_file(source) do
      File.write!(Path.join(directory, "#{module}.beam"), binary)
    end
  end

  defp compile_provenance(source, directory, elixir, otp) do
    {output, _status} =
      System.cmd("mise", ["exec", "elixir@#{elixir}", "erlang@#{otp}", "--", "elixirc", "-o", directory, source],
        stderr_to_stdout: true
      )

    # `mise exec` reports success even when the command it ran failed, so the beam itself is the evidence.
    if Path.wildcard(Path.join(directory, "*.beam")) == [],
      do: raise("compiling #{source} with Elixir #{elixir} produced no beam:\n#{output}")
  end

  defp provenance_source do
    """
    # #{@header}
    defmodule Provenance.Target do
      def snoc(q, x), do: {q, x}
    end

    defmodule Provenance do
      @doc "Appends x to q."
      def defaulted(a \\\\ nil, b \\\\ nil)
      def defaulted(a, b) when is_nil(a), do: {a, b}
      def defaulted(a, b), do: {a, b}

      def guarded(q, x) when is_list(q), do: {q, x}

      defmacro maked(a, b), do: quote(do: {unquote(a), unquote(b)})

      defdelegate delegated(q, x), to: Provenance.Target, as: :snoc

      # Precomposed, not decomposed: 1.11.4 rejects an unquoted identifier that is not already in NFC form, where
      # 1.20.4 accepts it and normalises. The matrix's own NFC world covers that difference on the pinned Elixir.
      def #{@precomposed}(q, x), do: {q, x}

      defp hidden(q), do: q
      def uses_hidden(q), do: hidden(q)
    end
    """
  end

  @definers [:def, :defp, :defmacro, :defmacrop, :defguard, :defguardp, :defdelegate]

  # The clause heads a feature should describe, read from real Elixir's parse of the declaring source. Taken here
  # rather than by quoting at test time so the tests ask the language nothing: the expectations are committed, the
  # pair that produced them is stamped, and the suite is then the same on every CI leg because nothing in it can
  # vary with the Elixir the leg happens to configure.
  defp heads(path) do
    text = File.read!(path)
    not_compiled = not_compiled_lines(text)

    {_ast, {heads, _attributes}} =
      text
      |> Code.string_to_quoted!(emit_warnings: false)
      |> Macro.prewalk({[], %{}}, fn
        # A module attribute a later EEx call may read its kind or its arguments from.
        {:@, _, [{attribute, _, [value]}]} = node, {acc, attributes} when attribute in [:kind, :args] ->
          {node, {acc, Map.put(attributes, attribute, value)}}

        # A function declared by a call: its kind, name and parameters are the call's arguments.
        {{:., _, [{:__aliases__, _, [:EEx]}, :function_from_string]}, _, [kind, name, _template, arguments | _]} = node, {acc, attributes} ->
          kind = attribute_value(kind, attributes)
          arguments = attribute_value(arguments, attributes)
          {node, {[head(kind, {name, [], Enum.map(arguments, &{&1, [], nil})}) | acc], attributes}}

        # An embed declares the atom plus a suffix: a template takes its assigns, a text nothing.
        {{:., _, [{:__aliases__, _, [:Mix, :Generator]}, kind]}, _, [base | _]} = node, {acc, attributes} when kind in [:embed_template, :embed_text] ->
          parameters = if kind == :embed_template, do: [{:assigns, [], nil}], else: []
          suffix = kind |> to_string() |> String.replace_prefix("embed", "")
          {node, {[head(:defp, {:"#{base}#{suffix}", [], parameters}) | acc], attributes}}

        # A definition under an `else` the condition never takes is never compiled, so it describes nothing.
        {definer, meta, [head | _]} = node, {acc, attributes} when definer in @definers ->
          if Map.has_key?(not_compiled, meta[:line]), do: {node, {acc, attributes}}, else: {node, {[head(definer, head) | acc], attributes}}
        node, acc -> {node, acc}
      end)

    heads |> Enum.reverse() |> Enum.reject(&is_nil/1)
  end

  # What a reader of the compiled artefact can honestly say about a definition, measured from the artefact rather
  # than declared. Debug info carries every clause as the author wrote it. A `Docs` chunk carries one signature per
  # definition - the author's parameter names, the defaults, and metadata saying whether it was a guard or a
  # delegate - but not the guard expression and not the other clauses; and a private function has no entry there at
  # all, so it falls through to the tables below. With neither chunk only the export and local tables survive: a
  # name, an arity, and a `MACRO-` prefix for a macro. Nothing in them records what a parameter was called, so the
  # expected parameter is `_`, which is how Elixir itself writes an argument that has no name. Rendering anything
  # else - `p0` included - would be the IDE inventing a name the author never chose, which is the one answer a
  # developer cannot act on.
  # Whether what the reader has is everything the author wrote: the source itself, or a beam that still carries its
  # debug info. False means something is gone for good - the guard, the other clauses, sometimes the parameter
  # names - and the reader owes the developer a word about it rather than quietly showing less.
  defp complete?(nil), do: true
  defp complete?(beam), do: beam |> File.read!() |> debug_info?()

  defp artefact_heads(heads, nil), do: heads

  defp artefact_heads(heads, beam) do
    binary = File.read!(beam)

    if debug_info?(binary) do
      heads
    else
      documented = documented_names(binary)
      {signatured, unnamed} = Enum.split_with(heads, &MapSet.member?(documented, &1["name"]))

      signatured
      |> Enum.uniq_by(&{&1["name"], length(&1["parameters"])})
      |> Enum.map(&%{&1 | "guard" => nil})
      |> Enum.concat(exported_heads(binary, unnamed))
    end
  end

  # Asked by making the backend produce the forms, not by looking for the chunk. A beam compiled without debug
  # info can still carry a `Dbgi` chunk that holds none - every Erlang beam here does - so the chunk's presence
  # says nothing, and the shape of what is inside it is the backend's business rather than this generator's.
  defp debug_info?(binary) do
    case :beam_lib.chunks(binary, [:debug_info]) do
      {:ok, {module, [debug_info: {:debug_info_v1, backend, data}]}} ->
        match?({:ok, _forms}, backend.debug_info(:erlang_v1, module, data, []))

      _ ->
        false
    end
  end

  defp documented_names(binary) do
    case :beam_lib.chunks(binary, [~c"Docs"], [:allow_missing_chunks]) do
      {:ok, {_module, [{~c"Docs", docs}]}} when is_binary(docs) ->
        {_tag, _anno, _language, _format, _module_doc, _metadata, entries} = :erlang.binary_to_term(docs)

        MapSet.new(entries, fn entry -> entry |> elem(0) |> elem(1) |> to_string() |> nfc() end)

      _ ->
        MapSet.new()
    end
  end

  # The export and local tables, as clause heads. A macro is exported under a `MACRO-` prefix and one arity higher,
  # for the caller's environment; a private function is local rather than exported. Nothing else about the
  # definition survives here, so nothing else is claimed.
  defp exported_heads(_binary, []), do: []

  defp exported_heads(binary, heads) do
    names = MapSet.new(heads, & &1["name"])
    {:ok, {_module, [exports: exports]}} = :beam_lib.chunks(binary, [:exports])
    {:ok, {_module, [locals: locals]}} = :beam_lib.chunks(binary, [:locals])

    (Enum.map(exports, &{&1, false}) ++ Enum.map(locals, &{&1, true}))
    |> Enum.map(fn {{name, arity}, private} -> exported_head(to_string(name), arity, private) end)
    |> Enum.filter(&MapSet.member?(names, &1["name"]))
    |> Enum.sort_by(&{&1["name"], length(&1["parameters"])})
  end

  defp exported_head("MACRO-" <> name, arity, private),
    do: unnamed_head(name, arity - 1, if(private, do: "defmacrop", else: "defmacro"))

  defp exported_head(name, arity, private),
    do: unnamed_head(name, arity, if(private, do: "defp", else: "def"))

  defp unnamed_head(name, arity, definer) do
    %{
      "definer" => definer,
      "name" => nfc(name),
      "parameters" => List.duplicate("_", arity),
      "defaults" => 0,
      "guard" => nil
    }
  end

  # `@name` read from the attributes set before it; anything else is itself.
  defp attribute_value({:@, _, [{attribute, _, context}]}, attributes) when is_atom(context), do: Map.fetch!(attributes, attribute)
  defp attribute_value(value, _attributes), do: value

  defp head(definer, {:when, _, [call, guard]}), do: head(definer, call, guard_string(guard))
  # A name written `unquote(:name)` is that name.
  defp head(definer, {{:unquote, _, [name]}, meta, arguments}) when is_atom(name), do: head(definer, {name, meta, arguments}, nil)
  defp head(definer, call), do: head(definer, call, nil)

  defp head(definer, {name, _, arguments}, guard) when is_atom(name) and is_list(arguments) do
    parameters = Enum.map(arguments, &parameter/1)

    %{
      "definer" => to_string(definer),
      "name" => nfc(to_string(name)),
      "parameters" => parameters,
      "defaults" => Enum.count(parameters, &String.contains?(&1, " \\\\ ")),
      "guard" => guard
    }
  end

  defp head(_definer, _call, _guard), do: nil

  defp parameter({:\\, _, [variable, default]}), do: "#{parameter(variable)} \\\\ #{Macro.to_string(default)}"
  defp parameter({name, _, context}) when is_atom(name) and is_atom(context), do: to_string(name)
  defp parameter(other), do: Macro.to_string(other)

  # A guard as the scenarios write it: a local call on variables, such as `is_list(q)`, joined by `or`/`and` infix, as
  # the source spells them; left-associated, so no parentheses are ever needed.
  defp guard_string({operator, _, [left, right]}) when operator in [:or, :and],
    do: "#{guard_string(left)} #{operator} #{guard_string(right)}"

  defp guard_string({name, _, arguments}) when is_atom(name) and is_list(arguments),
    do: "#{name}(#{Enum.map_join(arguments, ", ", &guard_string/1)})"

  defp guard_string({name, _, context}) when is_atom(name) and is_atom(context), do: to_string(name)
  defp guard_string(other), do: Macro.to_string(other)

  defp nfc(name), do: :unicode.characters_to_nfc_binary(name)

  # A module a `use` world's main module uses is written whole by `use_supports/6`.
  defp render_source(%{language: :elixir}, %{written: source}, _module, _definitions, _primary, _target), do: source

  defp render_source(%{language: :elixir}, form, module, definitions, primary, target),
    do: render_elixir(form, module, definitions, primary, target)

  defp render_source(%{language: :erlang}, form, module, definitions, primary, _target) do
    uses = if form[:private], do: private_uses(definitions, primary, :erlang), else: nil

    exports =
      definitions
      |> Enum.reject(fn _ -> form[:private] end)
      |> Enum.map(fn {name, [{parameters, _} | _]} -> "#{erlang_atom(name)}/#{length(parameters)}" end)
      |> Enum.uniq()
      |> Kernel.++(if primary, do: ["local_site/2"], else: [])
      |> Kernel.++(if uses, do: ["uses/2"], else: [])
      |> Enum.join(", ")

    functions =
      definitions
      |> Enum.group_by(fn {name, [{parameters, _} | _]} -> {name, length(parameters)} end)
      |> Enum.sort_by(fn {key, _} -> Enum.find_index(definitions, fn {name, [{parameters, _} | _]} -> {name, length(parameters)} == key end) end)
      |> Enum.map_join("\n\n", fn {_, group} ->
        group
        |> Enum.flat_map(fn {name, clauses} -> Enum.map(clauses, &{name, &1}) end)
        |> Enum.map_join(";\n", fn {name, {parameters, guard}} ->
          variables = Enum.map(parameters, &String.capitalize/1)
          guard = if guard, do: " when #{elem(guard, 0)}(#{String.capitalize(elem(guard, 1))})", else: ""
          "#{erlang_atom(name)}(#{Enum.join(variables, ", ")})#{guard} -> {#{Enum.join(variables, ", ")}}"
        end)
        |> Kernel.<>(".")
      end)

    local =
      if primary do
        {name, _} = primary
        "\n\nlocal_site(A, B) -> #{erlang_atom(name)}(A, B). % @local"
      else
        ""
      end

    uses = if uses, do: "\n\nuses(A, B) -> {#{uses}}.", else: ""

    """
    %% #{@header}
    -module(#{module}).
    -export([#{exports}]).

    #{functions}#{local}#{uses}
    """
  end

  # `to:` and any `as:`, in the spelling the form asks about.
  defp delegate_options(form, name, target) do
    as =
      case {form[:as], form[:as_written]} do
        {nil, _} -> []
        {_prefix, :attribute} -> ["as: @target"]
        {prefix, nil} -> ["as: :#{prefix}#{name}"]
      end

    options = Enum.join(["to: #{target}" | as], ", ")

    case form[:options] do
      :list -> "[#{options}]"
      :list_trailing -> "[#{options},]"
      :list_lines -> "[\n    #{options}\n  ]"
      nil -> options
    end
  end

  defp import_only({module, definitions}) do
    only =
      definitions
      |> Enum.map(fn {name, [first | _]} -> "#{name}: #{first |> clause_parts() |> elem(0) |> length()}" end)
      |> Enum.uniq()
      |> Enum.join(", ")

    "import #{module}, only: [#{only}], warn: false"
  end

  defp delegate_attribute(%{as_written: :attribute, as: prefix}, name), do: "  @target :#{prefix}#{name}\n"
  defp delegate_attribute(_form, _name), do: ""

  defp delegate_doc(%{doc: doc}), do: "  @doc #{inspect(doc)}\n"
  defp delegate_doc(_form), do: ""

  # `EEx.function_from_string` with its kind or its arguments written as a literal, or as a module attribute set on the line
  # before it.
  defp eex_function(form, name, variables) do
    template = "\"<%= inspect({#{Enum.join(variables, ", ")}}) %>\""
    arguments = "[#{Enum.map_join(variables, ", ", &(":" <> &1))}]"

    case form[:eex_attribute] do
      :kind -> "  @kind :#{form.definer}\n  EEx.function_from_string(@kind, :#{name}, #{template}, #{arguments})"
      :args -> "  @args #{arguments}\n  EEx.function_from_string(:#{form.definer}, :#{name}, #{template}, @args)"
      nil -> "  EEx.function_from_string(:#{form.definer}, :#{name}, #{template}, #{arguments})"
    end
  end

  defp erlang_atom(name), do: if(name =~ ~r/^[a-z][a-zA-Z0-9_]*$/, do: name, else: "'#{name}'")

  defp render_elixir(form, module, definitions, primary, target) do
    clauses = render_clauses(Map.put(form, :target, target), definitions)

    # A user of a `use` writes the `use`, and the quote it names writes the definitions.
    clauses = if form[:use], do: ["  use #{form.use.injector}#{form.use.argument}"], else: clauses

    render_module(form, module, definitions, primary, clauses)
  end

  # Each clause of [definitions] as its form writes it, two spaces in, the `if`/`else` of `x_if_else` included.
  defp render_clauses(form, definitions) do
    target = form[:target]

    clauses =
      for {{name, clauses}, definition_index} <- Enum.with_index(definitions), {clause, index} <- Enum.with_index(clauses) do
        {parameters, guard, head?} = clause_parts(clause)
        defaults = Enum.count(parameters, &is_tuple/1)

        # One `@spec` per arity the definition covers: with defaults it is one function at each of them.
        spec =
          if form[:spec] and index == 0,
            do:
              Enum.map_join((length(parameters) - defaults)..length(parameters)//1, fn arity ->
                "  @spec #{name}(#{Enum.join(List.duplicate("term()", arity), ", ")}) :: term() # @spec_#{arity}\n"
              end),
            else: ""
        written = if form[:unquote_name], do: "unquote(:#{name})", else: name
        rendered = Enum.map_join(parameters, ", ", fn {parameter, default} -> "#{parameter} \\\\ #{default}"; parameter -> parameter end)
        variables = Enum.map(parameters, fn {parameter, _} -> parameter; parameter -> parameter end)
        guard = if guard, do: " when #{elem(guard, 0)}(#{elem(guard, 1)})", else: ""

        cond do
          form[:parens] -> parenthesised(form, written, rendered, guard, variables, head?)
          # A bodiless head declares the defaults for the clauses that follow and defines nothing itself.
          head? -> "  #{form.definer} #{name}(#{rendered})"
          form[:delegate] -> "#{delegate_doc(form)}#{delegate_attribute(form, name)}  defdelegate #{name}(#{rendered}), #{delegate_options(form, name, target)}"
          form[:embed] && String.ends_with?(name, "_template") -> "  Mix.Generator.embed_template(:#{String.replace_suffix(name, "_template", "")}, \"<%= @q %>\")"
          form[:embed] -> "  Mix.Generator.embed_text(:#{String.replace_suffix(name, "_text", "")}, \"text\")"
          form[:eex] -> eex_function(form, name, variables)
          form[:guard] -> "  #{form.definer} #{name}(#{rendered}) when #{Enum.map_join(variables, " or ", &"is_list(#{&1})")}"
          form[:macro] -> "  #{form.definer} #{written}(#{rendered})#{guard}, do: quote(do: {#{Enum.map_join(variables, ", ", &"unquote(#{&1})")}})"
          true -> "  #{form.definer} #{written}(#{rendered})#{guard}, do: {#{Enum.join(variables, ", ")}}"
        end
        |> then(&{definition_index, spec <> &1})
      end

    # The first definition under a module-level `if`, the rest under its `else`, which is never compiled.
    clauses =
      if form[:branches] do
        {taken, other} = Enum.split_with(clauses, fn {definition_index, _} -> definition_index == 0 end)
        indent = &String.replace(elem(&1, 1), ~r/^/m, "  ")

        ["  if Code.ensure_loaded?(Kernel) do"] ++
          Enum.map(taken, indent) ++ ["  else"] ++ Enum.map(other, &(indent.(&1) <> " # @not_compiled")) ++ ["  end"]
      else
        Enum.map(clauses, &elem(&1, 1))
      end

    clauses
  end

  # A definition written as a call with its arguments in parentheses, as `__using__` quotes are sometimes written.
  defp parenthesised(form, name, rendered, guard, variables, head?) do
    cond do
      head? -> "  #{form.definer}(#{name}(#{rendered}))"
      form[:guard] -> "  #{form.definer}(#{name}(#{rendered}) when #{Enum.map_join(variables, " or ", &"is_list(#{&1})")})"
      form[:macro] -> "  #{form.definer}(#{name}(#{rendered})#{guard}, do: quote(do: {#{Enum.map_join(variables, ", ", &"unquote(#{&1})")}}))"
      true -> "  #{form.definer}(#{name}(#{rendered})#{guard}, do: {#{Enum.join(variables, ", ")}})"
    end
  end

  # [clauses], each two spaces in, under a wrapper's opening and closing lines.
  defp wrap(clauses, nil), do: clauses

  defp wrap(clauses, {opening, closing}),
    do: Enum.map(opening, &("  " <> &1)) ++ Enum.map(clauses, &String.replace(&1, ~r/^/m, "  ")) ++ Enum.map(closing, &("  " <> &1))

  defp wrap(clauses, {opening, closing, :list}) do
    {last, init} = List.pop_at(clauses, -1)
    wrap(Enum.map(init, &(&1 <> ",")) ++ [last], {opening, closing})
  end

  defp render_module(%{protocol: true} = form, module, definitions, _primary, _clauses) do
    heads = Enum.map_join(definitions, "\n", fn {name, [{parameters, _guard} | _]} -> "  def #{name}(#{Enum.join(parameters, ", ")})" end)

    """
    # #{@header}
    defprotocol #{module} do
    #{Enum.map_join(form.moduledoc, &("  " <> &1 <> "\n"))}
    #{heads}
    end
    """
  end

  defp render_module(form, module, definitions, primary, clauses) do
    # Under a module-level `if` and the like, which is how a definition that is only sometimes compiled is written.
    clauses = wrap(clauses, form[:wrapper])

    # A call made before the definition it calls, which a resolver walking the module top-down meets first.
    forward =
      if form[:local_forward] do
        {name, _} = primary
        "  def local_forward(a, b), do: #{nfc(name)}(a, b) # @local_forward\n\n"
      else
        ""
      end

    local =
      if primary do
        {name, _} = primary
        call = "#{nfc(name)}(#{arguments(local_arity(definitions, primary))})"
        parameters = Enum.map_join(["a", "b"], ", ", fn parameter -> if(call =~ ~r/\b#{parameter}\b/, do: parameter, else: "_" <> parameter) end)
        "\n\n  def local_site(#{parameters}), do: #{call} # @local"
      else
        ""
      end

    # One call per line, each marked, so every use it makes is a site the oracle binds: a rename has to reach them.
    uses =
      if primary && form[:private] do
        calls =
          definitions
          |> private_use_calls(primary)
          |> Enum.with_index()
          |> Enum.map_join(fn {{name, arity}, index} -> "\n      #{nfc(name)}(#{Enum.join(Enum.take(["a", "b", "a"], arity), ", ")}), # @uses_#{index}" end)

        "\n\n  def uses(a, b) do\n    {#{calls}\n      a,\n      b\n    }\n  end"
      else
        ""
      end

    # A delegate's target has no `local_site/2`; this gives it an ASCII-named definition too, so how its `.beam` was
    # built can be checked apart from how the decompiler reads the world's own names.
    marker = if String.ends_with?(module, ".Target"), do: "\n\n  def target_marker, do: :ok", else: ""
    requires =
      cond do
        form[:eex] -> "  require EEx\n\n"
        form[:embed] -> "  require Mix.Generator\n\n"
        # Brought in and never called here: `warn: false`, or the compiler would call the import unused.
        form[:imports] -> "  " <> import_only(form.imports) <> "\n\n"
        true -> ""
      end

    moduledoc = if lines = form[:moduledoc], do: Enum.map_join(lines, &("  " <> &1 <> "\n")) <> "\n", else: ""
    module_local = if form[:moduledoc], do: "\n\n  def module_local, do: #{module} # @module_local", else: ""

    """
    # #{@header}
    defmodule #{module} do
    #{moduledoc}#{requires}#{forward}#{Enum.join(clauses, "\n")}#{local}#{uses}#{marker}#{module_local}
    end
    """
  end

  # The calls of `private_use_calls/2` on one line, as Erlang's `uses/2` makes them.
  defp private_uses(definitions, primary, language) do
    definitions
    |> private_use_calls(primary)
    |> Enum.map_join(", ", fn {name, arity} ->
      arguments = ["a", "b", "a"] |> Enum.take(arity)

      case language do
        :elixir -> "#{nfc(name)}(#{Enum.join(arguments, ", ")})"
        :erlang -> "#{erlang_atom(name)}(#{arguments |> Enum.map(&String.upcase/1) |> Enum.join(", ")})"
      end
    end)
    |> case do
      "" -> ""
      uses -> uses <> ", "
    end
    |> Kernel.<>(if(language == :elixir, do: "a, b", else: "A, B"))
  end

  # Every private definition and arity other than what `local_site` calls, so the compiler warns about none.
  defp private_use_calls(definitions, primary) do
    {primary_name, _} = primary

    definitions
    |> Enum.flat_map(fn {name, [first | _]} ->
      {parameters, _, _} = clause_parts(first)
      defaults = Enum.count(parameters, &is_tuple/1)
      # `local_site` always passes two arguments, whatever the primary's own arity, so that is the one call already
      # made. Excluding the primary's full arity instead only coincided while every primary took two parameters.
      for arity <- (length(parameters) - defaults)..length(parameters), {name, arity} != {primary_name, local_arity(definitions, primary)}, do: {name, arity}
    end)
    |> Enum.uniq()
  end

  defp render_caller(backing, form, world, names, calls) do
    references = Enum.map(names, &reference(backing, &1))

    body =
      Enum.map_join(calls, "\n", fn
        {id, module, name, _arity, :module_defimpl} ->
          "  defimpl #{Enum.at(references, module)}, for: Integer do # @#{id}\n    def #{name}(q, x), do: {q, x}\n  end"

        {id, module, name, arity, shape} ->
          body = call(shape, backing, Enum.at(references, module), name, arity)
          parameters = Enum.map_join(["a", "b"], ", ", fn parameter -> if(body =~ ~r/\b#{parameter}\b/, do: parameter, else: "_" <> parameter) end)
          "  def at_#{id}(#{parameters}), do: #{body} # @#{id}"
      end)

    aliases =
      if backing.language == :elixir && !form[:private] do
        "  alias #{hd(references)}\n  alias #{hd(references)}, as: Aliased\n"
      else
        ""
      end

    uses =
      cond do
        form[:private] -> ""
        # Nothing in the caller would use them, and the compiler would warn.
        Enum.all?(calls, &(elem(&1, 4) in @module_atoms)) -> ""
        Enum.all?(calls, &(elem(&1, 4) in [:module_defimpl | @module_shapes])) -> "  alias #{hd(references)}\n"
        form[:macro] -> aliases <> Enum.map_join(references, "", &"  require #{&1}\n") <> "  import #{hd(references)}\n"
        true -> aliases <> "  import #{hd(references)}\n"
      end

    """
    # #{@header}
    defmodule Callers.#{Macro.camelize(backing.prefix)}.#{Macro.camelize(form.id)}.#{Macro.camelize(world)} do
    #{uses}
    #{body}
    end
    """
  end

  # No argument list at all. A different shape in the parser, and the only one the unresolved inspection looks at.
  defp call(:no_arguments, backing, module, name, _arity), do: "#{module}.#{call_name(backing, name)}"
  defp call(:qualified, backing, module, name, arity), do: "#{module}.#{call_name(backing, name)}(#{arguments(arity)})"
  defp call(:aliased, backing, module, name, arity), do: "#{last_segment(module)}.#{call_name(backing, name)}(#{arguments(arity)})"
  defp call(:aliased_as, backing, _module, name, arity), do: "Aliased.#{call_name(backing, name)}(#{arguments(arity)})"
  defp call(:unqualified, _backing, _module, name, arity), do: "#{name}(#{arguments(arity)})"
  defp call(:pipe, _backing, _module, name, arity), do: "a |> #{name}(#{arguments(arity - 1) |> String.replace_prefix("a", "b")})"
  defp call(:capture, backing, module, name, arity), do: "{&#{module}.#{call_name(backing, name)}/#{arity}, a, b}"
  defp call(:apply, _backing, module, name, arity), do: "apply(#{module}, :#{name}, [#{arguments(arity)}])"
  defp call(:apply_quoted, _backing, module, name, arity), do: "apply(#{module}, :\"#{name}\", [#{arguments(arity)}])"
  defp call(:mfa, _backing, module, name, arity), do: "{{#{module}, :#{name}, #{arity}}, a, b}"
  defp call(:variable, _backing, _module, name, _arity), do: "(fn #{name} -> #{name} end).({a, b})"
  defp call(:atom, _backing, _module, name, _arity), do: "{:#{name}, a, b}"
  defp call(:keyword, _backing, _module, name, _arity), do: "[#{name}: a, b: b]"
  defp call(:interpolated_atom, _backing, _module, name, _arity), do: ~s({:"#{name}", a, b})
  defp call(:module_atom, _backing, _module, name, _arity), do: "{:#{name}, a, b}"
  defp call(:module, _backing, module, _name, _arity), do: module
  defp call(:module_aliased, _backing, module, _name, _arity), do: last_segment(module)

  # Erlang keeps a decomposed name as written, so Elixir must quote it to call it; unquoted, it would normalise it.
  defp call_name(%{language: :erlang}, name), do: if(name == nfc(name), do: name, else: ~s("#{name}"))
  defp call_name(_backing, name), do: name

  defp arguments(arity), do: ["a", "b", "a"] |> Enum.take(arity) |> Enum.join(", ")

  defp last_segment(module), do: module |> String.split(".") |> List.last()

  defp compile_source(%{language: :elixir} = backing, module, path, source) do
    {[{_module, binary}], events} = compile_elixir_modules(path, source)
    {beam_path(backing, module, binary), events, binary}
  end

  defp compile_source(%{language: :erlang} = backing, module, path, _source) do
    options = [:binary, :return_errors, :return_warnings, :deterministic] ++ if(backing.debug_info, do: [:debug_info], else: [])

    {:ok, erlang_module, binary, warnings} = :compile.file(String.to_charlist(path), options)
    if warnings != [], do: raise("#{path} compiled with warnings: #{inspect(warnings)}")
    {:module, ^erlang_module} = :code.load_binary(erlang_module, String.to_charlist(path), binary)

    {beam_path(backing, module, binary), :erlang, binary}
  end

  defp beam_path(%{compiled: false}, _module, _binary), do: nil

  defp beam_path(backing, module, binary) do
    {:ok, name, chunks} = :beam_lib.all_chunks(binary)
    {:ok, stripped} = :beam_lib.build_module(Enum.reject(chunks, fn {id, _} -> id in backing.strip end))
    file = if(backing.language == :elixir, do: "Elixir." <> module, else: module) <> ".beam"
    ^name = if(backing.language == :elixir, do: String.to_atom("Elixir." <> module), else: String.to_atom(module))
    # Where Mix puts a dependency's beams, so the sandbox project sees them exactly as it would a real dependency.
    path = Path.join(["_build", "dev", "lib", backing.id, "ebin", file])
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, stripped)
    path
  end

  defp compile_elixir(path, source) do
    {_modules, events} = compile_elixir_modules(path, source)
    events
  end

  defp compile_elixir_modules(path, source) do
    Matrix.Events.take()
    {modules, diagnostics} = Code.with_diagnostics(fn -> Code.compile_string(source, path) end)
    # An unresolvable delegate's target is missing on purpose.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^\S+\.Missing\.\S+ is undefined \(module \S+\.Missing is not available/))
    # A target that only imports the function does not define it, on purpose.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^\S+\.DefdelegateImports\.\S+\.Target\.\S+ is undefined or private/))
    # A private definition injected into a second user that never calls it (or, like `hidden/1`, into any), a
    # `defmacrop __using__` no `use` can call, and the private function `x_use_apply`'s `__using__` reaches only
    # through `apply`. `@compile :nowarn_unused_function` does not silence these on 1.20.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^(function|macro) (\S+_x_use_\S+|__using__\/1|secret\/0) is unused/))
    # A module declared, and named, with quotes it does not need, on purpose.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^found quoted atom "\S+_x_interpolated_atom_quoted" but the quotes are not required/))
    # The quoted keyword a wrapper writes on purpose.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^found quoted keyword "else" but the quotes are not required/ and path =~ ~r/else_quoted/))
    # A moduledoc world setting the doc a second time, which is what it asks about.
    diagnostics = Enum.reject(diagnostics, &(&1.message =~ ~r/^redefining @moduledoc attribute/ and path =~ ~r/x_moduledoc/))
    if diagnostics != [], do: raise("#{path} compiled with diagnostics: #{inspect(diagnostics)}")
    {modules, Matrix.Events.take()}
  end

  defp caller_sites(path, source, events, calls, backing, names) do
    lines = source |> String.split("\n") |> Enum.with_index(1)

    Enum.map(calls, fn
      {id, module, _name, _arity, :module_defimpl} ->
        {text, line} = Enum.find(lines, fn {text, _} -> String.ends_with?(text, "# @#{id}") end)
        [_, qualifier, protocol, for_module] = Regex.run(~r/^\s*defimpl ((?:\S+\.)?)([^\s.,]+), for: (\S+) do/, text)
        # No alias reference is traced at a `defimpl`'s protocol, so the protocol is the one its implementation names.
        implementation = Module.concat(Enum.at(names, module), for_module)

        %{
          "id" => id,
          "file" => path,
          "line" => line,
          "column" => utf16_length(hd(String.split(text, "defimpl ")) <> "defimpl " <> qualifier) + 1,
          "name" => protocol,
          "arity" => 0,
          "binding" => %{"module" => inspect(implementation.__impl__(:protocol)), "name" => inspect(implementation.__impl__(:protocol)), "arity" => 0, "kind" => "alias_reference"}
        }

      {id, module, name, arity, shape} ->
        {text, line} = Enum.find(lines, fn {text, _} -> String.ends_with?(text, "# @#{id}") end)
        # A module is asked at its own name, the alias's last segment: an earlier one names a module of its own.
        name = if shape in @module_shapes, do: last_segment(Enum.at(names, module)), else: name
        binding = binding(events, path, line, name, shape, backing, Enum.at(names, module), arity)

        site = %{
          "id" => id,
          "file" => path,
          "line" => line,
          "column" => name_column(text, name),
          "name" => nfc(name),
          "arity" => arity,
          "binding" => binding
        }

        if shape in @module_atoms, do: Map.put(site, "targets", atom_targets(lines, name)), else: site
    end)
  end

  # The lines declaring the module the atom evaluates to; none where no module has that name.
  defp atom_targets(lines, name) do
    atom = atom(~s(:"#{name}"))
    for {text, line} <- lines, [_, declared] <- [Regex.run(~r/^defmodule (.+) do end$/, text)], atom(declared) == atom, do: line
  end

  # Quotes the atom does not need are the point of some sites, so the warning they draw is not wanted here.
  defp atom(source), do: source |> Code.string_to_quoted!(emit_warnings: false) |> Code.eval_quoted() |> elem(0)

  # The compiler binds nothing at the atom in `apply(M, :name, [...])`, but the plugin treats that atom as a
  # reference to M.name/length([...]), and so does this oracle. A variable, a bare atom and a keyword key bind to no
  # definition.
  defp binding(_events, _path, _line, name, shape, backing, module, arity) when shape in [:apply, :apply_quoted, :mfa],
    do: %{"module" => reference(backing, module), "name" => nfc(name), "arity" => arity, "kind" => to_string(shape)}

  defp binding(_events, _path, _line, _name, shape, _backing, _module, _arity) when shape in @not_calls, do: nil

  defp binding(events, path, line, _name, shape, _backing, _module, _arity) when shape in @module_shapes, do: module_binding(events, path, line)

  defp binding(events, path, line, name, _shape, _backing, _module, _arity) do
    atom = String.to_atom(name)

    case Enum.filter(events, &(&1.file |> Path.relative_to_cwd() == path and &1.line == line and &1.name in [atom, String.to_atom(nfc(name))])) do
      [event] -> %{"module" => inspect(event.module), "name" => to_string(event.name), "arity" => event.arity, "kind" => to_string(event.kind)}
      events -> raise("#{path}:#{line} has #{length(events)} traced calls to #{name}: #{inspect(events)}")
    end
  end

  # Erlang is compiled without the Elixir tracer, but its only marked call is `local_site`'s local call.
  defp local_sites(path, source, events, backing, module, {name, _}, arity) do
    lines = source |> String.split("\n") |> Enum.with_index(1)
    {text, line} = Enum.find(lines, fn {text, _} -> String.ends_with?(text, "@local") end)

    binding =
      if events == :erlang do
        %{"module" => reference(backing, module), "name" => name, "arity" => arity, "kind" => "local_function"}
      else
        binding(events, path, line, nfc(name), :local, backing, module, arity)
      end

    [
      %{
        "id" => "local",
        "file" => path,
        "line" => line,
        "column" => name_column(text, nfc(name)),
        "name" => nfc(name),
        "arity" => arity,
        "binding" => binding
      }
    ]
  end

  # The declaring file's other marked places: a call placed before its definition, and each `@spec`'s name, which
  # the compiler binds to nothing but names one arity of one function all the same.
  defp marked_sites(path, source, events, backing, module) do
    for {text, line} <- source |> String.split("\n") |> Enum.with_index(1),
        [_, id] <- [Regex.run(~r/# @(local_forward|spec_\d+|uses_\d+)$/, text)] do
      cond do
        String.starts_with?(id, "uses_") ->
          [_, {name_start, name_length}, {arguments_start, arguments_length}] = Regex.run(~r/^\s*([^\s(]+)\(([^)]*)\)/u, text, return: :index)
          name = binary_part(text, name_start, name_length)
          arguments = binary_part(text, arguments_start, arguments_length)
          arity = if arguments == "", do: 0, else: arguments |> String.split(",") |> length()

          %{
            "id" => id,
            "file" => path,
            "line" => line,
            "column" => utf16_length(binary_part(text, 0, name_start)) + 1,
            "name" => nfc(name),
            "arity" => arity,
            "binding" => binding(events, path, line, nfc(name), :local, backing, module, arity)
          }

        id == "local_forward" ->
          [_, name] = Regex.run(~r/do: ([^\s(]+)\(/u, text)

          %{
            "id" => id,
            "file" => path,
            "line" => line,
            "column" => name_column(text, name),
            "name" => nfc(name),
            "arity" => 2,
            "binding" => binding(events, path, line, nfc(name), :local, backing, module, 2)
          }

        true ->
          [_, {name_start, name_length}] = Regex.run(~r/@spec ([^\s(]+)\(/u, text, return: :index)
          name = binary_part(text, name_start, name_length)
          arity = id |> String.replace_prefix("spec_", "") |> String.to_integer()

          %{
            "id" => id,
            "file" => path,
            "line" => line,
            "column" => utf16_length(binary_part(text, 0, name_start)) + 1,
            "name" => nfc(name),
            "arity" => arity,
            "binding" => %{"module" => reference(backing, module), "name" => nfc(name), "arity" => arity, "kind" => "spec"}
          }
      end
    end
  end

  # The module an alias at [line] expands to, as the compiler traced it.
  defp module_binding(events, path, line) do
    case Enum.filter(events, &(&1.kind == :alias_reference and &1.file |> Path.relative_to_cwd() == path and &1.line == line)) do
      [event] -> %{"module" => inspect(event.module), "name" => inspect(event.module), "arity" => 0, "kind" => "alias_reference"}
      events -> raise("#{path}:#{line} has #{length(events)} traced alias references: #{inspect(events)}")
    end
  end

  # A moduledoc world's places in its own module, each at the module's last segment: the reference `module_local`
  # makes, and the `defmodule`'s name, which is the module the compiler defined.
  defp module_sites(path, source, events, binary) do
    lines = source |> String.split("\n") |> Enum.with_index(1)
    {declaration_text, declaration_line} = Enum.find(lines, fn {text, _} -> String.starts_with?(text, ["defmodule ", "defprotocol "]) end)
    [_, definer, qualifier, declared] = Regex.run(~r/^(defmodule |defprotocol )((?:\S+\.)?)(\S+) do$/, declaration_text)
    {:ok, {defined, _}} = :beam_lib.chunks(binary, [])

    local =
      case Enum.find(lines, fn {text, _} -> String.ends_with?(text, "# @module_local") end) do
        nil ->
          []

        {local_text, local_line} ->
          [_, local_name] = Regex.run(~r/do: (?:\S+\.)?(\S+) #/, local_text)

          [
            %{
              "id" => "module_local",
              "file" => path,
              "line" => local_line,
              "column" => name_column(local_text, local_name),
              "name" => local_name,
              "arity" => 0,
              "binding" => module_binding(events, path, local_line)
            }
          ]
      end

    local ++
      [
        %{
          "id" => "module_declaration",
          "file" => path,
          "line" => declaration_line,
          "column" => String.length(definer <> qualifier) + 1,
          "name" => declared,
          "arity" => 0,
          "binding" => %{"module" => inspect(defined), "name" => inspect(defined), "arity" => 0, "kind" => "defmodule"}
        }
      ]
  end

  # `local_site` calls the primary's name with two arguments wherever some definition of it takes two, which is every
  # world but `x_embed`, whose template takes one.
  defp local_arity(definitions, {name, _}) do
    arities =
      for {^name, [first | _]} <- definitions, {parameters, _, _} = clause_parts(first),
          arity <- (length(parameters) - Enum.count(parameters, &is_tuple/1))..length(parameters),
          do: arity

    if 2 in arities, do: 2, else: Enum.max(arities)
  end

  # A site's column is where the target's name starts after `do:` (or `->` in Erlang), or on a line of a function body
  # that is only the call, counted in UTF-16 code units as the IDE's document offsets are.
  defp name_column(text, name) do
    body_start =
      case Regex.run(~r/do: |-> /, text, return: :index) do
        [{start, _}] -> start
        nil -> 0
      end

    escaped = Regex.escape(name)
    pattern = ~r/(?<![\w.:?!"])#{escaped}(?![\w?!\x{0300}-\x{036F}])|(?<=[.:"])#{escaped}(?![\w?!\x{0300}-\x{036F}])/u
    [{start, _}] = Regex.run(pattern, text, return: :index, offset: body_start)
    utf16_length(binary_part(text, 0, start)) + 1
  end

  defp utf16_length(text), do: text |> :unicode.characters_to_binary(:utf8, :utf16) |> byte_size() |> div(2)

  # The lines of definitions written where they are never compiled, which `generate.exs` marks `# @not_compiled`.
  defp not_compiled_lines(text) do
    for {line, index} <- text |> String.split("\n") |> Enum.with_index(1), String.ends_with?(line, "# @not_compiled"), into: %{}, do: {index, true}
  end

  defp declarations(source) do
    lines = String.split(source, "\n")

    lines
    |> Enum.with_index(1)
    |> Enum.reject(fn {text, _line} -> String.ends_with?(text, "# @not_compiled") end)
    |> Enum.map(fn {text, line} -> {eex_with_attribute(text, Enum.at(lines, line - 2, "")), line} end)
    |> Enum.flat_map(fn {text, line} ->
      # `\s*$` matches a bodiless head, which declares the defaults and defines nothing.
      # An EEx function's name is the atom after its kind, and its parameters the atoms in its last list.
      case Regex.run(~r/^\s*(def|defp|defmacro|defmacrop) unquote\(:([^\s)]+)\)\((.*?)\)(?: when |, do:)/u, text, return: :index) ||
             Regex.run(~r/^\s*(def|defp|defmacro|defmacrop|defguard|defguardp|defdelegate) ([^\s(]+)\((.*?)\)(?: when |, do:|, to:|, \[to:|, \[$|\s*$)/u, text, return: :index) ||
             Regex.run(~r/^\s*(def|defp|defmacro|defmacrop|defguard|defguardp)\(([^\s(]+)\((.*?)\)(?: when |, do:|\)$)/u, text, return: :index) ||
             Regex.run(~r/^\s*EEx\.function_from_string\(\s*:(def|defp), :([^\s,]+), .*, \[(.*)\]\)$/u, text, return: :index) do
        [_, {definer_start, definer_length}, {name_start, name_length}, {parameters_start, parameters_length}] ->
          name = binary_part(text, name_start, name_length)
          parameters = binary_part(text, parameters_start, parameters_length) |> String.split(", ", trim: true)

          if name in ["local_site", "local_forward", "uses", "__using__"] do
            []
          else
            [%{"name" => nfc(name), "arity" => length(parameters), "definer" => binary_part(text, definer_start, definer_length), "line" => line, "column" => utf16_length(binary_part(text, 0, name_start)) + 1}]
          end

        nil ->
          embed_declaration(text, line)
      end
    end)
    |> Enum.group_by(&{&1["name"], &1["arity"]})
    |> Enum.flat_map(fn {_, clauses} -> clauses |> Enum.with_index() |> Enum.map(fn {clause, index} -> Map.put(clause, "clause", index) end) end)
    |> Enum.sort_by(&{&1["line"], &1["column"]})
  end

  # An EEx call reading its kind or arguments from the attribute set on the line before, as that line spells them: the
  # position of the name is unchanged, since the attribute is only ever the first or the last argument.
  defp eex_with_attribute(text, previous) do
    case {Regex.run(~r/^\s*@(kind|args) (.*)$/, previous), text} do
      # Padded to `@kind`'s length, so the name after it keeps its column.
      {[_, "kind", ":" <> kind], _} -> String.replace(text, "EEx.function_from_string(@kind, ", "EEx.function_from_string(#{String.pad_leading(":" <> kind, 5)}, ")
      {[_, "args", arguments], _} -> String.replace_suffix(text, ", @args)", ", #{arguments})")
      _ -> text
    end
  end

  # An embed's declaration is its atom, which names the function only with the suffix the kind adds.
  defp embed_declaration(text, line) do
    case Regex.run(~r/^\s*Mix\.Generator\.embed_(template|text)\(:([^\s,]+), /u, text, return: :index) do
      [_, {kind_start, kind_length}, {name_start, name_length}] ->
        kind = binary_part(text, kind_start, kind_length)
        name = binary_part(text, name_start, name_length) <> "_" <> kind
        arity = if kind == "template", do: 1, else: 0
        spelled = binary_part(text, name_start, name_length)
        [%{"name" => nfc(name), "spelled" => nfc(spelled), "arity" => arity, "definer" => "defp", "line" => line, "column" => utf16_length(binary_part(text, 0, name_start)) + 1}]

      nil ->
        []
    end
  end

  # Every file this script writes, found by walking the directories it wipes at the start rather than by listing
  # what the oracle happens to name. Enumerating the oracle's own keys left the broken callers and the provenance
  # beams unhashed - 155 files holding 259 marked sites - so a hand-edit to one of them moved hundreds of carets
  # with the guard still green. A fixture the oracle does not mention is exactly the one nothing else would catch.
  #
  # `oracle.json` is hashed too: it is the expectations themselves, so an edit to it is the one that changes what
  # the matrix asserts. It is written before this runs, so hashing it here is safe.
  defp manifest(_scenarios) do
    files =
      @generated_directories
      |> Enum.flat_map(&Path.wildcard(Path.join(&1, "**/*")))
      |> Enum.reject(&File.dir?/1)
      |> Kernel.++(["oracle.json"])
      |> Enum.sort()
      |> Map.new(&{&1, :crypto.hash(:sha256, File.read!(&1)) |> Base.encode16(case: :lower)})

    %{"header" => @header, "sha256" => files}
  end
end

Matrix.run()
