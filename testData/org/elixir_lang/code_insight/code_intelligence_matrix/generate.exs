    # name `snoc/1` as surely as a call does, and a rename that finds only the calls leaves them naming nothing.
    lower_arity_uses = [{"capture_1", 0, "snoc", 1, :capture}, {"apply_1", 0, "snoc", 1, :apply}, {"mfa_1", 0, "snoc", 1, :mfa}]

